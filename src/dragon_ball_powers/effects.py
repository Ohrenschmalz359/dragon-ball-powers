def _finite(x: Any, default: float = 0.0) -> float:
    """``float(x)`` if that is a finite number, else ``default``."""
    try:
        f = float(x)
    except (TypeError, ValueError, OverflowError):
        return default
    return f if math.isfinite(f) else default


def _to_vec(v: Any) -> Vec2 | None:
    """Convert a 2-sequence to a finite ``(x, y)`` tuple, ``None`` if that is impossible."""
    if v is None:
        return None
    try:
        x = float(v[0])
        y = float(v[1])
    except (TypeError, ValueError, IndexError, KeyError, OverflowError):
        return None
    if math.isfinite(x) and math.isfinite(y):
        return (x, y)
    return None


def _unit(v: Vec2 | None) -> Vec2 | None:
    if v is None:
        return None
    n = math.hypot(v[0], v[1])
    if n < 1e-9 or not math.isfinite(n):
        return None
    return (v[0] / n, v[1] / n)


def _wrap_angle(a: float) -> float:
    return (a + math.pi) % TAU - math.pi


def _ray_exit(origin: Vec2, d: Vec2, w: float, h: float) -> float:
    """Distance along unit ``d`` from ``origin`` to where the ray leaves the scene rectangle.

    Returns 0 when the ray never passes through the rectangle (slab method).
    """
    t_near, t_far = -math.inf, math.inf
    for o, dd, size in ((origin[0], d[0], w), (origin[1], d[1], h)):
        if abs(dd) < 1e-9:
            if o < 0.0 or o > size:
                return 0.0
            continue
        t1 = -o / dd
        t2 = (size - o) / dd
        if t1 > t2:
            t1, t2 = t2, t1
        t_near = max(t_near, t1)
        t_far = min(t_far, t2)
    if not math.isfinite(t_far) or t_far < max(t_near, 0.0):
        return 0.0
    return max(0.0, t_far)


def _perspective_squash(d: Vec2, k: float) -> Vec2:
    """Axis-aligned x/y scale approximating a ring around a beam with direction ``d``.

    A ring around the beam axis is seen from the side as an ellipse that is ``k`` times
    narrower along the beam. ``Ring`` only supports axis-aligned squash, so this returns
    the extents of that ellipse along x and y (exact for horizontal/vertical beams).
    """
    dx, dy = d
    return (math.sqrt((k * dx) ** 2 + dy * dy), math.sqrt((k * dy) ** 2 + dx * dx))


def _palette_lut(p: Palette) -> np.ndarray:
    inner = np.asarray(p.inner, np.float32)
