class _Pool:
    """Column-major struct-of-arrays storage for the particles of one sprite shape."""

    def __init__(self, shape: int, capacity: int = 256) -> None:
        self.shape = shape
        self.n = 0
        self.data = np.zeros((_NCOL, capacity), np.float32)
        self._alloc_out(capacity)

    def _alloc_out(self, capacity: int) -> None:
        # Output buffers reused by collect(); the sprite batches are views into them.
        self.out_pos = np.zeros((capacity, 2), np.float32)
        self.out_size = np.zeros(capacity, np.float32)
        self.out_col = np.zeros((capacity, 4), np.float32)
        self.out_vel = np.zeros((capacity, 2), np.float32)

    @property
    def capacity(self) -> int:
        return int(self.data.shape[1])

    def ensure(self, need: int) -> None:
        cap = self.capacity
        if need <= cap:
            return
        new_cap = max(int(need), cap * 2)
        data = np.zeros((_NCOL, new_cap), np.float32)
        data[:, : self.n] = self.data[:, : self.n]
        self.data = data
        self._alloc_out(new_cap)

    def keep(self, mask: np.ndarray) -> None:
        idx = np.flatnonzero(mask)
        k = int(idx.size)
        if k == self.n:
            return
        if k:
            self.data[:, :k] = self.data[:, idx]
        self.n = k

    def oldest(self, k: int) -> np.ndarray:
        """Indices of the ``k`` particles closest to the end of their life."""
        n = self.n
        if k <= 0 or n == 0:
            return np.empty(0, np.intp)
        if k >= n:
            return np.arange(n, dtype=np.intp)
        frac = self.data[_AGE, :n] / np.maximum(self.data[_LIFE, :n], 1e-6)
        return np.argpartition(-frac, k - 1)[:k].astype(np.intp)

    def kill_oldest(self, k: int) -> int:
        k = min(int(k), self.n)
        if k <= 0:
            return 0
        if k == self.n:
            self.n = 0
            return k
        mask = np.ones(self.n, bool)
        mask[self.oldest(k)] = False
        self.keep(mask)
        return k


class _ParticleSystem:
    """All particle pools, the global budget and the orb attractor table."""

    MAX_ATTRACTORS = 32

    def __init__(self, cap: int, scene_size: tuple[int, int], rng: np.random.Generator) -> None:
        self.rng = rng
        self.pools = [_Pool(i) for i in range(len(SpriteShape))]
        self.cap = max(1, int(cap))
        self.scene_w = float(scene_size[0])
        self.scene_h = float(scene_size[1])
        self.speed_limit = 8000.0 * self.scene_h / 720.0
        self.att = np.zeros((self.MAX_ATTRACTORS, 4), np.float32)   # x, y, radius, infall gain
        self.att_active = np.zeros(self.MAX_ATTRACTORS, bool)

    # ------------------------------------------------------------------ budget

    @property
    def total(self) -> int:
        return sum(p.n for p in self.pools)

    def counts(self) -> dict[str, int]:
        return {SpriteShape(p.shape).name.lower(): p.n for p in self.pools}

    def clear(self) -> None:
        for p in self.pools:
            p.n = 0
        self.att_active[:] = False

    def set_cap(self, cap: int) -> None:
        self.cap = max(1, int(cap))
        excess = self.total - self.cap
        if excess > 0:
            self._evict(excess, None)

    def set_bounds(self, w: int, h: int) -> None:
        self.scene_w = float(w)
        self.scene_h = float(h)
        self.speed_limit = 8000.0 * self.scene_h / 720.0

    def _evict(self, k: int, exclude: _Pool | None) -> int:
        """Kill the ``k`` oldest particles of the other pools, proportionally to their size."""
        candidates = [p for p in self.pools if p is not exclude and p.n > 0]
        avail = sum(p.n for p in candidates)
        if avail == 0 or k <= 0:
            return 0
        k = min(int(k), avail)
        freed = 0
        for p in candidates:
            share = min(p.n, k - freed, int(math.ceil(k * p.n / avail)))
            if share > 0:
                freed += p.kill_oldest(share)
        if freed < k:  # rounding: take the rest from whatever is left
            for p in candidates:
                if freed >= k:
                    break
                freed += p.kill_oldest(min(p.n, k - freed))
        return freed

    def _reserve(self, pool: _Pool, n: int, replace: bool) -> slice | np.ndarray:
        n = min(int(n), self.cap)
        free = self.cap - self.total
        if n <= free:
            start = pool.n
            pool.ensure(start + n)
            pool.n = start + n
            return slice(start, start + n)
        if not replace:
            take = max(0, free)
            start = pool.n
            if take:
                pool.ensure(start + take)
                pool.n = start + take
            return slice(start, start + take)
        # Important one-shot effect: overwrite the oldest particles of this pool first,
        # then evict from the other pools if that is still not enough.
        deficit = n - max(free, 0)
        k_self = min(deficit, pool.n)
        deficit -= k_self
        if deficit > 0:
            free = max(free, 0) + self._evict(deficit, pool)
        n_new = min(n - k_self, max(free, 0))
        old = pool.oldest(k_self)
        start = pool.n
        pool.ensure(start + n_new)
        pool.n = start + n_new
        return np.concatenate((np.arange(start, start + n_new, dtype=np.intp), old))

    # -------------------------------------------------------------- attractors

    def acquire_attractor(self) -> int:
        free = np.flatnonzero(~self.att_active)
        if free.size == 0:
            return -1
        slot = int(free[0])
        self.att_active[slot] = True
        self.att[slot] = (0.0, 0.0, 1.0, 1.0)
        return slot

    def set_attractor(self, slot: int, center: Vec2, radius: float, infall: float | None = None) -> None:
        if 0 <= slot < self.MAX_ATTRACTORS:
            row = self.att[slot]
            row[0] = center[0]
            row[1] = center[1]
            row[2] = max(radius, 0.5)
            if infall is not None:
                row[3] = infall

    def release_attractor(self, slot: int, life_left: float = 0.3, kick: float = 0.0) -> None:
        """Detach all particles of ``slot`` (they keep their velocity and fade out quickly)."""
        if not (0 <= slot < self.MAX_ATTRACTORS) or not self.att_active[slot]:
            return
        ax, ay = float(self.att[slot, 0]), float(self.att[slot, 1])
        for pool in self.pools:
            n = pool.n
            if n == 0:
                continue
            D = pool.data
            idx = np.flatnonzero(D[_ATT, :n] == slot)
            if idx.size == 0:
                continue
            D[_ATT, idx] = -1.0
            D[_LIFE, idx] = np.minimum(D[_LIFE, idx], D[_AGE, idx] + life_left)
            if kick:
                dx = D[_PX, idx] - ax
                dy = D[_PY, idx] - ay
                inv = kick / np.maximum(np.hypot(dx, dy), 1e-3)
                D[_VX, idx] += dx * inv
                D[_VY, idx] += dy * inv
        self.att_active[slot] = False

    # ------------------------------------------------------------------- emit

    def emit(self, shape: int, pos: np.ndarray, vel: np.ndarray | None, life: Any, size0: Any, size1: Any, *,
             col_a: Any = ROLE_INNER, col_b: Any = ROLE_CORE, col_t: Any = 0.0, int0: Any = 1.0,
             int1: Any = 1.0, drag: Any = 0.0, grav: Any = 0.0, fade_in: Any = 0.05, flicker: Any = 0.0,
             age: Any = None, orbit: tuple | None = None, replace: bool = False) -> int:
        """Spawn particles (fields: scalars or arrays of length N). Returns the number emitted.

        ``replace=False`` (continuous emitters) only uses free budget; ``replace=True``
        (one-shot impacts) overwrites the oldest particles when the budget is full.
        Particles with any non-finite field are rejected, so pool data is always finite.
        """
        n = min(int(pos.shape[0]), self.cap)
        if n <= 0 or (not replace and self.total >= self.cap):
            return 0
        block = np.repeat(_DEFAULTS_COL, n, axis=1)
        block[_PX] = pos[:n, 0]
        block[_PY] = pos[:n, 1]
        if vel is not None:
            block[_VX] = vel[:n, 0]
            block[_VY] = vel[:n, 1]
        _put(block, _LIFE, life, n)
        _put(block, _S0, size0, n)
        _put(block, _S1, size1, n)
        _put(block, _CA, col_a, n)
        _put(block, _CB, col_b, n)
        _put(block, _CT, col_t, n)
        _put(block, _I0, int0, n)
        _put(block, _I1, int1, n)
        _put(block, _DRAG, drag, n)
        _put(block, _GRAV, grav, n)
        _put(block, _FIN, fade_in, n)
        np.maximum(block[_LIFE], 0.01, out=block[_LIFE])     # t = age / life must stay finite
        np.maximum(block[_FIN], 1e-3, out=block[_FIN])
        sizes = block[_S0:_S1 + 1]
        np.maximum(sizes, 0.05, out=sizes)
        if isinstance(flicker, np.ndarray) or flicker:
            _put(block, _FLK, flicker, n)
            np.clip(block[_FLK], 0.0, 0.8, out=block[_FLK])   # intensity must stay positive
            block[_PH] = self.rng.random(n, dtype=np.float32) * np.float32(TAU)
        if orbit is not None:
            slot, r, ang, w, v, tilt, cr, sr = orbit
            block[_ATT] = slot
            _put(block, _OR, r, n)
            _put(block, _OA, ang, n)
            _put(block, _OW, w, n)
            _put(block, _OV, v, n)
            _put(block, _OTL, tilt, n)
            _put(block, _OCR, cr, n)
            _put(block, _OSR, sr, n)
        if age is not None:
            # Sub-frame emission time: spread continuous streams evenly instead of in clumps.
            _put(block, _AGE, age, n)
            block[_PX] += block[_VX] * block[_AGE]
            block[_PY] += block[_VY] * block[_AGE]
        finite = np.isfinite(block)
        if not finite.all():
            good = finite.all(axis=0)
            log.debug("Rejected %d non-finite particles", int(n - good.sum()))
            block = block[:, good]
            n = int(block.shape[1])
            if n == 0:
                return 0
        pool = self.pools[shape]
        rows = self._reserve(pool, n, replace)
        m = (rows.stop - rows.start) if isinstance(rows, slice) else int(rows.size)
        if m <= 0:
            return 0
        pool.data[:, rows] = block if m == n else block[:, :m]
        return m

    # ----------------------------------------------------------------- update

    def update(self, dt: float) -> None:
        if not dt >= MIN_DT:   # also rejects NaN; attracted velocities divide by dt
            return
        w, h = self.scene_w, self.scene_h
        mx = 0.35 * w + 64.0
        my = 0.35 * h + 64.0
        for pool in self.pools:
            n = pool.n
            if n == 0:
                continue
            D = pool.data
            age = D[_AGE, :n]
            age += dt
            alive = age < D[_LIFE, :n]
            att_idx = np.flatnonzero(D[_ATT, :n] >= 0.0)
            old = D[_PX:_PY + 1, att_idx] if att_idx.size else None
            vel = D[_VX:_VY + 1, :n]
            vel *= np.exp(D[_DRAG, :n] * (-dt))
            vel[1] += D[_GRAV, :n] * dt
            D[_PX:_PY + 1, :n] += vel * dt
            if old is not None:
                self._update_attracted(D, att_idx, old, dt, alive)
            px = D[_PX, :n]
            py = D[_PY, :n]
            # Off-screen culling also removes NaN/inf positions (comparisons are False).
            alive &= (px > -mx) & (px < w + mx) & (py > -my) & (py < h + my)
            if not alive.all():
                pool.keep(alive)

    def _update_attracted(self, D: np.ndarray, idx: np.ndarray, old: np.ndarray, dt: float,
                          alive: np.ndarray) -> None:
        slots = D[_ATT, idx].astype(np.intp)
        np.clip(slots, 0, self.MAX_ATTRACTORS - 1, out=slots)
        A = self.att[slots]
        r = D[_OR, idx]
        v = D[_OV, idx]
        # Radial infall dr/dt = -v / sqrt(r): slow far out, accelerating towards the core.
        r_new = r - v * A[:, 3] * dt / np.sqrt(np.maximum(r, 0.2))
        rs = np.maximum(r_new, 0.2)
        # Angular speed grows as the particle falls in (w * r^-0.75): an accretion swirl.
        ang = D[_OA, idx] + D[_OW, idx] * dt * np.power(rs, -0.75)
        lx = r_new * np.cos(ang)
        ly = r_new * np.sin(ang) * D[_OTL, idx]
        cr = D[_OCR, idx]
        sr = D[_OSR, idx]
        R = A[:, 2]
        x = A[:, 0] + R * (lx * cr - ly * sr)
        y = A[:, 1] + R * (lx * sr + ly * cr)
        inv_dt = 1.0 / dt
        vx = (x - old[0]) * inv_dt
        vy = (y - old[1]) * inv_dt
        sp2 = vx * vx + vy * vy
        lim = self.speed_limit
        fast = sp2 > lim * lim
        if fast.any():  # an orb teleport must not produce screen-long streaks
            k = lim / np.sqrt(sp2[fast])
            vx[fast] *= k
            vy[fast] *= k
        D[_PX, idx] = x
        D[_PY, idx] = y
        D[_VX, idx] = vx
        D[_VY, idx] = vy
        D[_OR, idx] = r_new
        D[_OA, idx] = ang
        absorbed = (r_new < ABSORB_RADIUS) & (v > 0.0)
        if absorbed.any():
            alive[idx[absorbed]] = False

    def rescale(self, sx: float, sy: float) -> None:
        for pool in self.pools:
            n = pool.n
            if n == 0:
                continue
            D = pool.data
            D[_PX, :n] *= sx
            D[_PY, :n] *= sy
            D[_VX, :n] *= sx
            D[_VY, :n] *= sy
            D[_S0, :n] *= sy
            D[_S1, :n] *= sy
            D[_GRAV, :n] *= sy
        self.att[:, 0] *= sx
        self.att[:, 1] *= sy
        self.att[:, 2] *= sy

    # ---------------------------------------------------------------- collect

    def collect(self, sprites: list[SpriteBatch], lut: np.ndarray) -> None:
        for shape in _DRAW_ORDER:
            pool = self.pools[shape]
            n = pool.n
            if n == 0:
                continue
            D = pool.data
            t = D[_AGE, :n] / D[_LIFE, :n]
            np.clip(t, 0.0, 1.0, out=t)
            s0 = D[_S0, :n]
            sizes = pool.out_size[:n]
            np.subtract(D[_S1, :n], s0, out=sizes)
            sizes *= t
            sizes += s0
            i0 = D[_I0, :n]
            inten = (D[_I1, :n] - i0) * t
            inten += i0
            flk = D[_FLK, :n]
            if flk.any():
                inten *= 1.0 + flk * np.sin(D[_PH, :n] + 31.0 * D[_AGE, :n])
            alpha = np.minimum(t / D[_FIN, :n], 1.0)
            alpha *= 1.0 - t * t
            rgb = lut[D[_CA, :n].astype(np.intp)]
            rgb += (lut[D[_CB, :n].astype(np.intp)] - rgb) * D[_CT, :n, None]
            rgb *= inten[:, None]
            col = pool.out_col[:n]
            col[:, :3] = rgb
            col[:, 3] = alpha
            pos = pool.out_pos[:n]
            pos[:] = D[_PX:_PY + 1, :n].T
            if shape == _SPARK:
                vel = pool.out_vel[:n]
                vel[:] = D[_VX:_VY + 1, :n].T
                sprites.append(SpriteBatch(SpriteShape.SPARK, pos, sizes, col, vel, SPARK_STRETCH))
            else:
                sprites.append(SpriteBatch(SpriteShape(shape), pos, sizes, col))


