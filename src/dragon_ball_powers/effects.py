def _pose_silhouette(pose: PoseObservation, scene_w: int, scene_h: int, mask_w: int,
                     body_scale: float = 0.0, min_visibility: float = 0.3) -> tuple[np.ndarray, float] | None:
    """Draw a soft person mask from pose landmarks (fallback when no segmentation exists).

    The mask is ``mask_w`` wide (height by scene aspect) and aligned to the full scene:
    filled torso polygon (extended to below the frame when the hips are not visible),
    thick limb lines, wrist/hand blobs, neck and a head circle, then a Gaussian blur.
    Returns ``(mask, body_scale_px)`` or ``None`` when no usable landmark is visible.
    """
    try:
        lm = np.asarray(pose.landmarks, dtype=np.float64)
        vis = np.asarray(pose.visibility, dtype=np.float64).reshape(-1)
    except (TypeError, ValueError, AttributeError):
        return None
    if lm.ndim != 2 or lm.shape[0] < 33 or lm.shape[1] < 2:
        return None
    if vis.size < 33:
        vis = np.ones(33)
    mw = int(clamp(float(mask_w), 16.0, 2048.0))
    mh = max(8, int(round(mw * scene_h / max(scene_w, 1))))
    sx = mw / scene_w
    sy = mh / scene_h
    pts = lm[:33, :2] * (sx, sy)
    ok = (np.isfinite(pts).all(axis=1) & (vis[:33] >= min_visibility)
          & (np.abs(pts) < 4.0 * max(mw, mh)).all(axis=1))
    S = _finite(body_scale, 0.0) * sx
    if S <= 0.0:
        if ok[11] and ok[12]:
            S = float(np.hypot(*(pts[11] - pts[12])))
        else:
            S = 0.22 * mh
    S = clamp(S, 2.0, 2.0 * mh)
    mask = np.zeros((mh, mw), np.uint8)
    drew = False

    def P(i: int) -> tuple[int, int]:
        return (int(round(pts[i, 0])), int(round(pts[i, 1])))

    if ok[11] and ok[12]:
        left, right = pts[11], pts[12]
        if ok[23] and ok[24]:
            poly = np.array([left, right, pts[24], pts[23]])
        else:
            # Hips out of frame (typical webcam framing): the torso continues downwards.
            across = right - left
            down = np.array([-across[1], across[0]])
            if down[1] < 0:
                down = -down
            nrm = float(np.hypot(*down))
            down = down / nrm if nrm > 1e-6 else np.array([0.0, 1.0])
            ext = down * 2.6 * S
            poly = np.array([left, right, right + ext - across * 0.05, left + ext + across * 0.05])
        cv2.fillPoly(mask, [np.round(poly).astype(np.int32)], 255, cv2.LINE_AA)
        mid = (left + right) * 0.5
        if ok[0]:
            cv2.line(mask, (int(round(mid[0])), int(round(mid[1]))), P(0), 255,
                     max(1, int(round(0.42 * S))), cv2.LINE_AA)
        drew = True
    arm_t = max(1, int(round(0.36 * S)))
    leg_t = max(1, int(round(0.48 * S)))
    for a, b, t in ((11, 13, arm_t), (13, 15, arm_t), (12, 14, arm_t), (14, 16, arm_t),
                    (15, 19, arm_t), (16, 20, arm_t),
                    (23, 25, leg_t), (25, 27, leg_t), (24, 26, leg_t), (26, 28, leg_t)):
        if ok[a] and ok[b]:
            cv2.line(mask, P(a), P(b), 255, t, cv2.LINE_AA)
            drew = True
    for i in (15, 16):
        if ok[i]:
            cv2.circle(mask, P(i), max(1, int(round(0.24 * S))), 255, -1, cv2.LINE_AA)
            drew = True
    if ok[0]:
        head = (int(round(pts[0, 0])), int(round(pts[0, 1] - 0.15 * S)))
        cv2.circle(mask, head, max(1, int(round(0.5 * S))), 255, -1, cv2.LINE_AA)
        drew = True
    if not drew:
        return None
    k = int(max(3, round(S * 0.25))) | 1
    return cv2.GaussianBlur(mask, (k, k), 0), S / sx


def _hand_blobs(body: BodyState, scene_w: int, scene_h: int, mask_w: int, body_scale: float) -> np.ndarray | None:
    """Last-resort aura mask: soft blobs around the hand centres."""
    centers: list[tuple[Vec2, float]] = []
    for arm in (body.left, body.right):
        if not getattr(arm, "present", False):
            continue
        c = _to_vec(getattr(arm, "hand_center", None))
        if c is not None:
            centers.append((c, max(0.0, _finite(getattr(arm, "hand_size", 0.0), 0.0))))
    if not centers:
        return None
    mw = int(clamp(float(mask_w), 16.0, 2048.0))
    mh = max(8, int(round(mw * scene_h / max(scene_w, 1))))
    sx = mw / scene_w
    sy = mh / scene_h
    mask = np.zeros((mh, mw), np.uint8)
    rad_px = 0.0
    # The blob radius (and the blur kernel derived from it) must stay bounded: a garbage
    # hand size of 1e5 px made cv2 spend seconds per mask, 1e9 px ran out of memory.
    max_rad = 0.6 * mh
    for (x, y), hs in centers:
        rad = min(max(0.3 * body_scale, 0.7 * hs) * sx, max_rad)
        rad_px = max(rad_px, rad)
        if abs(x * sx) > 4 * mw or abs(y * sy) > 4 * mh:
            continue
        cv2.circle(mask, (int(round(x * sx)), int(round(y * sy))), max(1, int(round(rad))), 255, -1, cv2.LINE_AA)
    k = int(max(3, round(rad_px * 0.5))) | 1
    return cv2.GaussianBlur(mask, (k, k), 0)


def _mask_edges(mask: np.ndarray, scene_w: int, scene_h: int,
                max_points: int = MAX_EDGE_POINTS) -> tuple[np.ndarray, np.ndarray, Vec2 | None]:
    """Silhouette outline points (scene px), outward normals and the outline centroid."""
    mh, mw = mask.shape
    m = mask >= 110
    inner = m.copy()
    inner[1:, :] &= m[:-1, :]
    inner[:-1, :] &= m[1:, :]
    inner[:, 1:] &= m[:, :-1]
    inner[:, :-1] &= m[:, 1:]
    ys, xs = np.nonzero(m & ~inner)
    if ys.size == 0:
        empty = np.zeros((0, 2), np.float32)
        return empty, empty.copy(), None
    if ys.size > max_points:
        sel = np.linspace(0, ys.size - 1, max_points).astype(np.intp)
        ys = ys[sel]
        xs = xs[sel]
    gx = mask[ys, np.minimum(xs + 1, mw - 1)].astype(np.float32) - mask[ys, np.maximum(xs - 1, 0)]
    gy = mask[np.minimum(ys + 1, mh - 1), xs].astype(np.float32) - mask[np.maximum(ys - 1, 0), xs]
    ln = np.hypot(gx, gy)
    nrm = np.empty((ys.size, 2), np.float32)
    good = ln > 1e-3
    # The mask gradient points inwards (0 outside, 255 inside): outward = -gradient.
    nrm[:, 0] = np.where(good, -gx / np.maximum(ln, 1e-3), 0.0)
    nrm[:, 1] = np.where(good, -gy / np.maximum(ln, 1e-3), -1.0)
    pts = np.empty((ys.size, 2), np.float32)
    pts[:, 0] = (xs + 0.5) * (scene_w / mw)
    pts[:, 1] = (ys + 0.5) * (scene_h / mh)
    centroid = (float(pts[:, 0].mean()), float(pts[:, 1].mean()))
    return pts, nrm, centroid


class AuraEffect(_Effect):
    """Flame-like power aura hugging the user's silhouette (create with :meth:`EffectSystem.create_aura`).

    Call :meth:`set` every tick. Mask sources in order of preference: the segmentation
    ``mask`` (uint8, any resolution, aligned to the scene), a silhouette synthesised from
    the ``pose`` landmarks, blobs around the hands of ``body``. :meth:`end` fades it out
    over 0.4 s. Read-only: ``alive``, ``intensity``, ``mask_id``.
    """

    transient = False
    RISE = 5.0
    FALL = 3.0
    END_TIME = 0.4
    STALE_TIME = 0.5
    SYNTH_INTERVAL = 1.0 / 45.0
    MAX_ARCS = 3

    def __init__(self, system: EffectSystem) -> None:
        super().__init__(system)
        self._target = 0.0
        self._intensity = 0.0
        self._energy = 0.0
        self._target_energy = 0.0
        self._mask: np.ndarray | None = None
        self._mask_id = 0
        self._source = "none"           # "mask" | "pose" | "hands" | "none"
        self._source_id: int | None = None
        self._pose_ref: Any = None
        self._body_ref: Any = None
        self._synth_time = -1e9
        self._no_source = 0.0
        self._scale = 0.22 * system._scene_h
        self._edges_for: int | None = None
        self._edge_pts = np.zeros((0, 2), np.float32)
        self._edge_nrm = np.zeros((0, 2), np.float32)
        self._centroid: Vec2 | None = None
        self._ending = False
        self._end_age = 0.0
        self._end_from = 0.0
        self._arcs: list[list[Any]] = []   # [slot, a, b, life_left, life_total]
        self._arc_timer = 0.0

    @property
    def intensity(self) -> float:
        return self._intensity

    @property
    def mask_id(self) -> int:
        return self._mask_id

    def set(self, intensity: float, mask: np.ndarray | None, mask_id: int, pose: PoseObservation | None,
            body: BodyState | None) -> None:
        """Update the aura: target intensity (0..1, smoothed) and the current silhouette sources."""
        if not self._alive or self._ending:
            return
        sys = self._sys
        self._target = clamp(_finite(intensity, 0.0), 0.0, 2.0)
        if body is not None:
            self._target_energy = clamp(_finite(getattr(body, "energy", 0.0), 0.0))
            bs = _finite(getattr(body, "body_scale", 0.0), 0.0)
            if bs > 0.0:
                self._scale = clamp(bs, 4.0, 2.0 * sys._scene_h)
        try:
            ok = False
            if mask is not None:
                ok = self._use_mask(mask, mask_id)
            if not ok and pose is not None:
                ok = self._use_pose(pose, body)
            if not ok and body is not None:
                ok = self._use_hands(body)
        except Exception:  # noqa: BLE001 - a bad mask must never break the frame
            sys._error_once("aura-source", "Could not build the aura mask")
            ok = False
        if ok:
            self._no_source = 0.0

    def end(self) -> None:
        """Fade the aura out over 0.4 s, then die."""
        if self._alive and not self._ending:
            self._ending = True
            self._end_age = 0.0
            self._end_from = self._intensity

    # ---------------------------------------------------------------- sources

    def _use_mask(self, mask: Any, mask_id: Any) -> bool:
        mid = int(_finite(mask_id, 0.0))
        if self._source == "mask" and self._source_id == mid and self._mask is not None:
            return True
        m = _mask_to_u8(mask)
        if m is None:
            self._sys._warn("aura-mask", "Ignoring unusable aura mask (shape/dtype)")
            return False
        self._mask = m
        self._mask_id = mid
        self._source = "mask"
        self._source_id = mid
        return True

    def _use_pose(self, pose: PoseObservation, body: BodyState | None) -> bool:
        sys = self._sys
        if self._source == "pose" and self._mask is not None:
            if pose is self._pose_ref or sys.time - self._synth_time < self.SYNTH_INTERVAL:
                return True
        has_scale = body is not None and _finite(getattr(body, "body_scale", 0.0), 0.0) > 0.0
        res = _pose_silhouette(pose, sys._scene_w, sys._scene_h, sys._quality.aura_resolution,
                               self._scale if has_scale else 0.0)
        if res is None:
            return False
        mask, scale = res
        if not has_scale:
            self._scale = clamp(scale, 4.0, 2.0 * sys._scene_h)
        self._set_synth(mask, "pose")
        self._pose_ref = pose
        return True

    def _use_hands(self, body: BodyState) -> bool:
        sys = self._sys
        if self._source == "hands" and self._mask is not None:
            if body is self._body_ref or sys.time - self._synth_time < self.SYNTH_INTERVAL:
                return True
        mask = _hand_blobs(body, sys._scene_w, sys._scene_h, sys._quality.aura_resolution, self._scale)
        if mask is None:
            return False
        self._set_synth(mask, "hands")
        self._body_ref = body
        return True

    def _set_synth(self, mask: np.ndarray, kind: str) -> None:
        self._mask = mask
        self._mask_id = self._sys._next_mask_id()
        self._source = kind
        self._source_id = None
        self._synth_time = self._sys.time

    def _ensure_edges(self) -> None:
        if self._mask is None or self._edges_for == self._mask_id:
            return
        sys = self._sys
        mask = self._mask
        if mask.shape[1] > 512:
            # A full-resolution mask is fine for the renderer, but outline sampling only
            # needs a coarse version (the tracker normally delivers ~256 px wide masks).
            h = max(8, int(round(mask.shape[0] * 256 / mask.shape[1])))
            mask = cv2.resize(mask, (256, h), interpolation=cv2.INTER_AREA)
        self._edge_pts, self._edge_nrm, self._centroid = _mask_edges(mask, sys._scene_w, sys._scene_h)
        self._edges_for = self._mask_id

    # ------------------------------------------------------------- simulation

    def _step(self, dt: float) -> None:
        super()._step(dt)
        sys = self._sys
        if self._ending:
            self._end_age += dt
            u = self._end_age / self.END_TIME
            if u >= 1.0:
                self._kill()
                return
            self._intensity = self._end_from * (1.0 - u)
        else:
            rate = self.RISE if self._target > self._intensity else self.FALL
            self._intensity = damp(self._intensity, self._target, rate, dt)
            if self._target == 0.0 and self._intensity < 1e-4:
                self._intensity = 0.0
            self._no_source += dt
            if self._no_source > self.STALE_TIME and self._mask is not None:
                # Nobody to wrap the aura around any more (user left the frame).
                self._mask = None
                self._source = "none"
                self._arcs.clear()
        self._energy = damp(self._energy, self._target_energy, 4.0, dt)
        # lightning crawling around the outline at very high power
        rng = sys.rng
        for arc in self._arcs:
            arc[3] -= dt
            slot = arc[0]
            slot.timer -= dt
            if slot.timer <= 0.0 and arc[3] > 0.0:
                sys._regen_arc(slot, math.hypot(arc[2][0] - arc[1][0], arc[2][1] - arc[1][1]), jaggedness=0.3,
                               branch_prob=0.15, visible_prob=0.9)
        self._arcs = [a for a in self._arcs if a[3] > 0.0]
        q = max(0, int(sys._quality.arc_count))
        if self._intensity > 0.9 and q > 0 and self._mask is not None and not self._ending:
            self._ensure_edges()
            count = self._edge_pts.shape[0]
            self._arc_timer -= dt
            if count and self._arc_timer <= 0.0 and len(self._arcs) < min(self.MAX_ARCS, q):
                self._arc_timer = float(rng.uniform(0.12, 0.35)) / (0.5 + self._intensity)
                i = int(rng.integers(0, count))
                px, py = float(self._edge_pts[i, 0]), float(self._edge_pts[i, 1])
                ang = math.atan2(float(self._edge_nrm[i, 1]), float(self._edge_nrm[i, 0])) + float(
                    rng.uniform(-1.1, 1.1))
                length = float(rng.uniform(0.25, 0.6)) * self._scale
                b = (px + math.cos(ang) * length, py + math.sin(ang) * length)
                slot = _ArcSlot()
                sys._regen_arc(slot, length, jaggedness=0.3, branch_prob=0.15, visible_prob=0.9)
                life = float(rng.uniform(0.1, 0.2))
                self._arcs.append([slot, (px, py), b, life, life])

    def _emit(self, dt: float) -> None:
        intensity = self._intensity
        if dt <= 0.0 or intensity < 0.02 or self._mask is None:
            return
        self._ensure_edges()
        if self._edge_pts.shape[0] == 0:
            return
        sys = self._sys
        dens = sys._density
        n = self._take(0, 90.0 * intensity * dens * (0.7 + 0.6 * self._energy) * dt)
        if n:
            self._emit_edge(_EMBER, n, intensity, dt)
        n = self._take(1, 60.0 * intensity * dens * dt)
        if n:
            self._emit_edge(_GLOW, n, intensity, dt)

    def _emit_edge(self, shape: int, n: int, intensity: float, dt: float) -> None:
        sys = self._sys
        rng = sys.rng
        ss = sys.scene_scale
        idx = rng.integers(0, self._edge_pts.shape[0], n)
        r = rng.random((7, n), dtype=np.float32)
        pos = self._edge_pts[idx] + (r[0:2].T - 0.5) * (3.0 * ss)
        nrm = self._edge_nrm[idx]
        lift = 0.6 + 0.6 * min(intensity, 1.5)
        vel = np.empty((n, 2), np.float32)
        if shape == _EMBER:
            out_spd = (15.0 + 45.0 * r[2]) * ss
            vel[:, 0] = nrm[:, 0] * out_spd
            vel[:, 1] = nrm[:, 1] * out_spd - (50.0 + 100.0 * r[3]) * ss * lift
            size0 = (1.0 + 1.2 * r[4]) * ss
            sys._particles.emit(_EMBER, pos, vel, 0.5 + 0.7 * r[5], size0, 0.5 * size0, col_a=ROLE_INNER,
                                col_b=ROLE_CORE, col_t=0.6 * r[6], int0=1.6, int1=0.4, drag=1.2,
                                grav=-(60.0 + 80.0 * r[4]) * ss, fade_in=0.12, flicker=0.4, age=r[6] * dt,
                                replace=False)
        else:
            out_spd = (10.0 + 30.0 * r[2]) * ss
            vel[:, 0] = nrm[:, 0] * out_spd
            vel[:, 1] = nrm[:, 1] * out_spd - (80.0 + 120.0 * r[3]) * ss * lift
            k = clamp(math.sqrt(self._scale / (0.3 * sys._scene_h)), 0.6, 1.6)
            size0 = (5.0 + 6.0 * r[4]) * ss * k
            sys._particles.emit(_GLOW, pos, vel, 0.3 + 0.3 * r[5], size0, 0.4 * size0, col_a=ROLE_OUTER,
                                col_b=ROLE_INNER, col_t=0.3 + 0.7 * r[6], int0=0.55, int1=0.05, drag=1.5,
                                grav=-100.0 * ss, fade_in=0.2, age=r[6] * dt, replace=False)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        intensity = self._intensity
        if self._mask is None or intensity < 0.005:
            return
        sys = self._sys
        pal = sys._palette
        en = self._energy
        prim = Aura(mask=self._mask, mask_id=self._mask_id, palette=pal, intensity=intensity, time=self._age,
                    flame_height=0.06 + 0.06 * clamp(intensity), turbulence=0.8 + 0.8 * en,
                    flicker=0.35 + 0.65 * en)
        if out.aura is None or out.aura.intensity < intensity:
            out.aura = prim
        for slot, a, b, life_left, life_total in self._arcs:
            if not slot.visible:
                continue
            k = math.sqrt(max(life_left, 0.0) / life_total)
            sys._add_arc(out, slot, a, b, slot.width * 0.85, (1.3 + 2.5 * (intensity - 0.9)) * slot.gain * k, 1.2)
        self._ensure_edges()
        if self._centroid is not None:
            lights.append((self._centroid[0], self._centroid[1], 2.5 * self._scale, 0.35 * intensity))

    def _rescale(self, sx: float, sy: float) -> None:
        self._edges_for = None    # outline points are in scene px
        self._scale *= sy
        # A synthesised mask has the old scene aspect: rebuild it on the next set() (even
        # for the same pose object), like after a quality change.
        self._quality_changed()
        for arc in self._arcs:
            arc[1] = (arc[1][0] * sx, arc[1][1] * sy)
            arc[2] = (arc[2][0] * sx, arc[2][1] * sy)

    def _finishing(self) -> bool:
        return not self._alive or self._ending

    def _finish(self) -> None:
        self.end()

    def _visible(self) -> bool:
        # A dormant aura handle (intensity 0, e.g. kept for auto mode) must not keep the grade active.
        return self._alive and self._mask is not None and self._intensity >= 0.005

    def _quality_changed(self) -> None:
        # Synthesised masks follow quality.aura_resolution: regenerate on the next set().
        self._pose_ref = None
        self._body_ref = None
        self._synth_time = -1e9


