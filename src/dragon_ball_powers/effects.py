def _place(norm: np.ndarray, a: Vec2, b: Vec2) -> np.ndarray:
    """Map a bolt in normalised chord coordinates (u along, v across) onto ``a -> b``.

    ``P = a + u (b - a) + v perp(b - a)`` written as one 2x2 matrix product.
    """
    dx = b[0] - a[0]
    dy = b[1] - a[1]
    out = norm @ np.array(((dx, dy), (-dy, dx)), np.float32)
    out += np.array(a, np.float32)
    return out


def _put(block: np.ndarray, col: int, value: Any, m: int) -> None:
    """Fill one particle field from a scalar or an array (scalar defaults are already there)."""
    if isinstance(value, np.ndarray) and value.ndim > 0:
        block[col] = value[:m]
    elif value != _DEFAULT_VALUES[col]:
        block[col] = value


