class EffectSystem:
    """Simulates every energy effect and emits backend-neutral primitives (see the module docs).

    Args:
        settings: effect settings (palette, multipliers, toggles); copied, change them
            with :meth:`apply_settings`.
        quality: quality preset (particle budget, arc count, aura resolution).
        scene_size: (width, height) of the scene (camera frame) in px.
        seed: random seed (identical calls produce identical output).
    """

    def __init__(self, settings: EffectsSettings, quality: QualityPreset, scene_size: tuple[int, int],
                 seed: int = 0) -> None:
        self.rng = np.random.default_rng(seed)
        if not _usable_settings(settings):
            log.warning("Invalid effect settings %r; using defaults", settings)
            settings = EffectsSettings()
        self._settings = _copy_settings(settings)
        sanitized = _sanitize_quality(quality)
        if sanitized is None:
            log.warning("Invalid quality preset %r; using 'high'", quality)
            sanitized = get_quality("high")
        self._quality = sanitized
        self._palette = get_palette(self._settings.energy_color)
        self._lut = _palette_lut(self._palette)
        self._scene_w, self._scene_h = _sanitize_size(scene_size)
        self._particles = _ParticleSystem(self._budget(), (self._scene_w, self._scene_h), self.rng)
        self._effects: list[_Effect] = []
        self._rings: list[_RingSim] = []
        self._flashes: list[_FlashSim] = []
        self._shaker = _Shaker(self.rng)
        self._grade = _GradeState()
        self._pending_lights: list[tuple[float, float, float, float]] = []
        self._frame_lights: list[tuple[float, float, float, float]] = []
        self._mask_counter = 0
        self._warned: set[str] = set()
        self.time = 0.0   # simulation clock (s): sum of the clamped dt values
        self.now = 0.0    # last ``now`` passed to update() (perf_counter seconds)

    # ------------------------------------------------------------ properties

    @property
    def palette(self) -> Palette:
        """Current energy palette."""
        return self._palette

    @property
    def scene_scale(self) -> float:
        """``scene_h / 720``: multiply pixel sizes designed for 720p by this."""
        return self._scene_h / 720.0

    @property
    def scene_size(self) -> tuple[int, int]:
        return (self._scene_w, self._scene_h)

    @property
    def particle_count(self) -> int:
        """Live particles across all pools (never above :attr:`particle_budget`)."""
        return self._particles.total

    @property
    def particle_budget(self) -> int:
        """Hard particle cap: ``quality.particle_budget x settings.particle_multiplier``."""
        return self._particles.cap

    @property
    def quality(self) -> QualityPreset:
        return self._quality

    @property
    def settings(self) -> EffectsSettings:
        """The settings in use (a private copy; change them with :meth:`apply_settings`)."""
        return self._settings

    @property
    def stats(self) -> dict[str, int]:
        """Counters for the debug overlay."""
        data = {"particles": self._particles.total, "budget": self._particles.cap,
                "effects": len(self._effects), "rings": len(self._rings), "flashes": len(self._flashes)}
        data.update(self._particles.counts())
        return data

    @property
    def _density(self) -> float:
        # Emission-rate multiplier relative to the "high" budget (quality x particle_multiplier).
        return clamp(self._particles.cap / REFERENCE_BUDGET, 0.15, 6.0)

    @property
    def _spark_density(self) -> float:
        return clamp(self._density, 0.25, 3.0)

    # ---------------------------------------------------------- configuration

    def set_scene_size(self, size: tuple[int, int]) -> None:
        """The camera frame size changed: rescale running effects to the new scene."""
        w, h = _sanitize_size(size, (self._scene_w, self._scene_h))
        if (w, h) == (self._scene_w, self._scene_h):
            return
        sx = w / self._scene_w
        sy = h / self._scene_h
        self._scene_w, self._scene_h = w, h
        self._particles.set_bounds(w, h)
        self._particles.rescale(sx, sy)
        for eff in self._effects:
            eff._rescale(sx, sy)
        for ring in self._rings:
            ring.rescale(sx, sy)
        for fl in self._flashes:
            fl.rescale(sx, sy)
        log.debug("Effect scene size set to %dx%d", w, h)

    def set_quality(self, preset: QualityPreset) -> None:
        """Switch quality: new particle budget (trimmed immediately), arc count, aura resolution.

        An unusable preset is ignored with a warning (the previous one stays active).
        """
        sanitized = _sanitize_quality(preset)
        if sanitized is None:
            self._warn("quality", "Ignoring invalid quality preset %r", preset)
            return
        self._quality = sanitized
        self._particles.set_cap(self._budget())
        for eff in self._effects:
            eff._quality_changed()

    def apply_settings(self, settings: EffectsSettings) -> None:
        """Apply effect settings: palette, multipliers and toggles take effect immediately.

        Anything that is not an :class:`EffectsSettings` is ignored with a warning.
        """
        if not _usable_settings(settings):
            self._warn("settings", "Ignoring invalid effect settings %r", settings)
            return
        self._settings = _copy_settings(settings)
        palette = get_palette(self._settings.energy_color)
        if palette is not self._palette:
            self._palette = palette
            self._lut = _palette_lut(palette)
        self._particles.set_cap(self._budget())

    def _budget(self) -> int:
        mult = clamp(_finite(self._settings.particle_multiplier, 1.0), 0.1, 3.0)
        return max(1, int(round(self._quality.particle_budget * mult)))

    # -------------------------------------------------------------- per frame

    def update(self, dt: float, now: float) -> None:
        """Advance every effect by ``dt`` seconds (clamped to 0.1 s) and drop finished ones.

        Negative, non-finite and sub-microsecond ``dt`` values count as 0: velocities are
        estimated as displacement / dt, so a near-zero step would overflow them.
        """
        dt = _finite(dt, 0.0)
        dt = MAX_DT if dt > MAX_DT else (0.0 if dt < MIN_DT else dt)
        self.now = _finite(now, self.now)
        self.time += dt
        self._frame_lights = self._pending_lights
        self._pending_lights = []
        effects = list(self._effects)
        for eff in effects:
            if eff.alive:
                self._guard(eff, eff._step, dt)
        self._particles.update(dt)
        for eff in effects:
            if eff.alive:
                self._guard(eff, eff._emit, dt)
        self._effects = [e for e in self._effects if e.alive]
        for ring in self._rings:
            ring.step(dt)
        self._rings = [r for r in self._rings if r.alive]
        for fl in self._flashes:
            fl.step(dt)
        self._flashes = [f for f in self._flashes if f.alive]
        self._shaker.step(dt)
        running = bool(self._rings or self._flashes or self._particles.total or self._shaker.active
                       or any(e._visible() for e in self._effects))
        self._grade.step(dt, running)

    def collect(self, out: RenderList) -> None:
        """Append this frame's primitives to ``out`` and set its shake, grade, bloom, lights and aura.

        The sprite batches (and aura mask) may be views of internal buffers: consume them
        before the next :meth:`update` and never modify them.
        """
        marks = {name: len(getattr(out, name)) for name in _PRIMITIVE_LISTS}
        lights = list(self._frame_lights)
        for eff in self._effects:
            if eff.alive:
                self._guard(eff, eff._collect, out, lights)
        pal = self._palette
        for ring in self._rings:
            prim = ring.primitive(pal)
            if prim is not None:
                out.rings.append(prim)
        for fl in self._flashes:
            v = fl.value()
            if v > 1e-3:
                out.flashes.append(Flash(intensity=v, color=self._flash_color(fl.tint), center=fl.center,
                                         radius=fl.radius))
        self._particles.collect(out.sprites, self._lut)
        excess = len(out.arcs) - marks["arcs"] - MAX_ARCS
        if excess > 0:
            del out.arcs[len(out.arcs) - excess:]
        out.shake = self._shaker.offset(self._scene_h, clamp(_finite(self._settings.screen_shake, 1.0), 0.0, 2.0))
        out.grade = self._grade.output(self._settings, pal, self.scene_scale)
        out.bloom = clamp(_finite(self._settings.bloom_strength, 1.0), 0.0, 3.0)
        self._output_lights(out, lights)
        self._sanitize(out, marks)

    def clear(self) -> None:
        """Remove every effect immediately (all handles die); the grade returns to identity."""
        for eff in self._effects:
            eff._kill()
        self._effects.clear()
        self._rings.clear()
        self._flashes.clear()
        self._particles.clear()
        self._shaker.clear()
        self._grade.reset()
        self._pending_lights.clear()
        self._frame_lights = []

    # ------------------------------------------------------- steerable effects

    def create_orb(self, center: Vec2, radius: float) -> OrbEffect:
        """Start a charging ki orb at ``center`` (it ignites small and swells to ``radius``)."""
        c = self._vec(center, "orb center") or self._scene_center()
        orb = OrbEffect(self, self._clamp_pos(c), self._len_value(radius, 30.0 * self.scene_scale))
        self._add_handle(orb)
        return orb

    def create_beam(self, origin: Vec2, direction: Vec2, width: float, power: float) -> BeamEffect:
        """Fire a lateral beam from ``origin`` along ``direction`` (``width`` = base half-width px)."""
        o = self._vec(origin, "beam origin") or self._scene_center()
        d = _unit(self._vec(direction, "beam direction")) or (1.0, 0.0)
        # Sanity cap: even a huge orb must not produce a beam that covers the whole picture.
        w = min(self._len_value(width, 30.0 * self.scene_scale), 0.3 * self._scene_h)
        beam = BeamEffect(self, self._clamp_pos(o), d, w, self._power_value(power))
        self._add_handle(beam)
        return beam

    def create_frontal_beam(self, center: Vec2, radius: float, power: float) -> FrontalBeamEffect:
        """Fire a beam towards the camera; its disc grows from ``radius`` to ~0.27 scene heights."""
        c = self._vec(center, "frontal beam center") or self._scene_center()
        beam = FrontalBeamEffect(self, self._clamp_pos(c), self._len_value(radius, 30.0 * self.scene_scale),
                                 self._power_value(power))
        self._add_handle(beam)
        return beam

    def create_aura(self) -> AuraEffect:
        """Create a power aura (invisible until :meth:`AuraEffect.set` gives it intensity and a silhouette)."""
        aura = AuraEffect(self)
        self._add_handle(aura)
        return aura

    # --------------------------------------------------- fire-and-forget effects

    def ki_blast(self, origin: Vec2, direction: Vec2, frontal: float, radius: float, power: float) -> None:
        """Throw the charged orb: towards the camera when ``frontal`` >= 0.55, else across the screen."""
        o = self._vec(origin, "ki blast origin")
        if o is None:
            return
        o = self._clamp_pos(o)
        d = _unit(self._vec(direction, "ki blast direction")) or (1.0, 0.0)
        f = clamp(_finite(frontal, 0.0))
        r = self._len_value(radius, 30.0 * self.scene_scale)
        p = self._power_value(power)
        if f >= 0.55:
            self._add_transient(_FrontalBlast(self, o, r, p))
        else:
            self._add_transient(_LateralBlast(self, o, d, r, p))

    def burst(self, center: Vec2, radius: float, power: float) -> None:
        """Energy burst: blinding flash, 3 staggered rings, hundreds of sparks, radial arcs, shake."""
        c = self._vec(center, "burst center")
        if c is None:
            return
        c = self._clamp_pos(c)
        ss = self.scene_scale
        h = self._scene_h
        R = self._len_value(radius, 40.0 * ss)
        p = self._power_value(power)
        p1 = min(p, 1.0)
        self.flash(1.0 + 0.5 * p, center=c, radius=max(0.6 * h, 4.0 * R), duration=0.25)
        self._add_flash(0.28 + 0.17 * p1, None, 0.0, 0.2, tint=0.25)
        r_end = R * (4.0 + 4.0 * p1)
        for k, delay in enumerate((0.0, 0.08, 0.18)):
            self._add_ring(_RingSim(c, R * (0.8 + 0.3 * k), r_end * (1.0 + 0.2 * k), 0.6 + 0.1 * k,
                                    thickness=max(4.0 * ss, 0.35 * R * (1.0 - 0.2 * k)),
                                    intensity=(1.6 + p) * (1.0 - 0.25 * k),
                                    refraction=lerp(6.0, 14.0, p1) * ss * (1.0 - 0.2 * k), noise=0.55,
                                    delay=delay))
        speed_hi = (900.0 + 900.0 * p1) * ss
        self._spray(_SPARK, c, int((200 + 400 * p1) * self._density), (0.35 * speed_hi, speed_hi), inner=0.5 * R,
                    size=(1.0 * ss, 2.4 * ss), life=(0.35, 0.9), drag=2.2, grav=90.0 * ss, intensity=(2.8, 0.3),
                    replace=True)
        self._spray(_EMBER, c, int(90 * self._density), (100.0 * ss, 600.0 * ss), inner=0.6 * R,
                    size=(1.0 * ss, 2.4 * ss), life=(0.8, 1.6), drag=1.5, grav=-40.0 * ss, intensity=(2.2, 0.3),
                    colors=(ROLE_INNER, ROLE_CORE), flicker=0.35, replace=True)
        self._spray(_SMOKE, c, 10, (40.0 * ss, 160.0 * ss), inner=0.8 * R, size=(0.7 * R, 1.1 * R), size_end=2.2,
                    life=(0.7, 1.2), drag=1.4, grav=-25.0 * ss, intensity=(0.3, 0.0), colors=(ROLE_SMOKE, ROLE_OUTER),
                    mix=(0.0, 0.35), fade_in=0.2, replace=True)
        q = max(0, int(self._quality.arc_count))
        if q > 0:
            n_arcs = min(6 + int(round(6 * p1)), max(6, 2 * q))
            self._add_transient(_RadialArcs(self, c, R, n_arcs, 0.2, 2.2 + 0.6 * p))
        self.shake(0.025 + 0.02 * p, 0.6)
        self._light_pulse(c, max(10.0 * R, 0.8 * h), 3.0 + p, 0.6)
        self._grade.pulse(3.0 * ss * (0.5 + 0.5 * p1), 0.03 * (0.5 + 0.5 * p1))

    def shockwave(self, center: Vec2, radius: float, power: float, speed: float | None = None) -> None:
        """Expanding ring from ``radius`` to ~``radius x (4 + 4 power)`` (0.6 s, or at ``speed`` px/s)."""
        c = self._vec(center, "shockwave center")
        if c is None:
            return
        c = self._clamp_pos(c)
        ss = self.scene_scale
        R = self._len_value(radius, 30.0 * ss)
        p = self._power_value(power)   # 0..1.5
        p1 = min(p, 1.0)
        r1 = R * (4.0 + 4.0 * p)
        duration = 0.6
        if speed is not None:
            spd = _finite(speed, 0.0)
            if spd > 0.0:
                duration = clamp((r1 - R) / spd, 0.15, 2.5)
        self._add_ring(_RingSim(c, R, r1, duration, thickness=max(3.0 * ss, 0.3 * R * (0.8 + 0.4 * p1)),
                                intensity=1.0 + 0.8 * p, refraction=8.0 * p * ss, noise=0.5))

    def flash(self, intensity: float, center: Vec2 | None = None, radius: float = 0.0,
              duration: float = 0.25) -> None:
        """Screen flash (radial around ``center`` when given); ~20 ms attack, decay over ``duration``."""
        value = clamp(_finite(intensity, 0.0), 0.0, 10.0)
        if value <= 0.0:
            return
        c: Vec2 | None = None
        if center is not None:
            c = self._vec(center, "flash center")
            if c is None:
                return
            c = self._clamp_pos(c)
        r = max(0.0, _finite(radius, 0.0))
        if c is not None and r <= 0.0:
            r = 0.6 * self._scene_h
        self._add_flash(value, c, min(r, 8.0 * max(self._scene_w, self._scene_h)),
                        clamp(_finite(duration, 0.25), 0.02, 5.0), tint=0.3)

    def shake(self, amplitude: float, duration: float) -> None:
        """Camera shake; ``amplitude`` is a fraction of the scene height (x settings.screen_shake)."""
        a = clamp(_finite(amplitude, 0.0), 0.0, 0.2)
        if a <= 0.0:
            return
        self._shaker.add(a, clamp(_finite(duration, 0.3), 0.02, 5.0))

    def sparks(self, center: Vec2, count: int, speed: float, direction: Vec2 | None = None,
               spread: float = math.tau, power: float = 1.0) -> None:
        """Spray ``count`` sparks (scaled by the particle density) at up to ``speed`` px/s."""
        c = self._vec(center, "sparks center")
        if c is None:
            return
        n = int(round(clamp(_finite(count, 0.0), 0.0, 5000.0) * self._spark_density))
        if n <= 0:
            return
        ss = self.scene_scale
        spd = clamp(_finite(speed, 0.0), 0.0, 20000.0 * ss)
        p = self._power_value(power)
        d = _unit(self._vec(direction, "sparks direction")) if direction is not None else None
        spr = clamp(_finite(spread, TAU), 0.0, TAU) if d is not None else TAU
        k = 0.8 + 0.2 * p
        self._spray(_SPARK, self._clamp_pos(c), n, (0.35 * spd, spd), direction=d, spread=spr,
                    size=((0.9 + 0.3 * p) * ss, (1.6 + 0.6 * p) * ss), life=(0.25 * k, 0.6 * k), drag=2.8,
                    grav=120.0 * ss, intensity=(1.4 + 0.8 * p, 0.3), replace=True)

    def fizzle(self, center: Vec2, radius: float) -> None:
        """A cancelled charge dissipates: spark scatter, smoke puff, embers and a small flash."""
        c = self._vec(center, "fizzle center")
        if c is None:
            return
        c = self._clamp_pos(c)
        R = self._len_value(radius, 25.0 * self.scene_scale)
        self._fizzle_particles(c, R, 1.0)
        self.flash(0.3, center=c, radius=2.5 * R, duration=0.15)

    def set_grade(self, darken: float, desaturate: float = 0.0) -> None:
        """Request a colour grade for this frame (0..1 each, max of all requests wins, smoothed)."""
        self._grade.request(clamp(_finite(darken, 0.0)), clamp(_finite(desaturate, 0.0)))

    def add_light(self, position: Vec2, radius: float, intensity: float) -> None:
        """Add a palette-coloured scene light for the next collected frame."""
        p = self._vec(position, "light position")
        if p is None:
            return
        r = _finite(radius, 0.0)
        i = _finite(intensity, 0.0)
        if r <= 0.0 or i <= 0.0 or len(self._pending_lights) >= MAX_PENDING_LIGHTS:
            return
        p = self._clamp_pos(p)
        self._pending_lights.append((p[0], p[1], min(r, 8.0 * max(self._scene_w, self._scene_h)), min(i, 8.0)))

    # ------------------------------------------------------------- internals

    def _guard(self, eff: _Effect, fn: Any, *args: Any) -> None:
        """Run one effect method; a failing effect is killed instead of breaking the frame."""
        try:
            fn(*args)
        except Exception:  # noqa: BLE001
            self._error_once(f"effect-{type(eff).__name__}", "Effect %s failed and was removed",
                             type(eff).__name__)
            try:
                eff._kill()
            except Exception:  # noqa: BLE001
                eff._alive = False

    def _warn(self, key: str, msg: str, *args: Any) -> None:
        if key in self._warned:
            log.debug(msg, *args)
        else:
            self._warned.add(key)
            log.warning(msg + " (further occurrences are logged at debug level)", *args)

    def _error_once(self, key: str, msg: str, *args: Any) -> None:
        if key in self._warned:
            log.debug(msg, *args)
        else:
            self._warned.add(key)
            log.exception(msg, *args)

    def _vec(self, v: Any, what: str) -> Vec2 | None:
        out = _to_vec(v)
        if out is None and v is not None:
            self._warn(f"vec-{what}", "Ignoring invalid %s: %r", what, v)
        return out

    def _clamp_pos(self, p: Vec2) -> Vec2:
        w, h = self._scene_w, self._scene_h
        return (clamp(p[0], -4.0 * w, 5.0 * w), clamp(p[1], -4.0 * h, 5.0 * h))

    def _len_value(self, x: Any, default: float) -> float:
        v = _finite(x, -1.0)
        if v <= 0.0:
            return default
        return clamp(v, 0.5, 4.0 * max(self._scene_w, self._scene_h))

    @staticmethod
    def _power_value(x: Any, default: float = 1.0) -> float:
        return clamp(_finite(x, default), 0.0, 1.5)

    def _scene_center(self) -> Vec2:
        return (0.5 * self._scene_w, 0.5 * self._scene_h)

    def _next_mask_id(self) -> int:
        self._mask_counter += 1
        return SYNTH_MASK_ID_BASE + self._mask_counter

    def _add_handle(self, eff: _Effect) -> None:
        """Register a steerable effect; a runaway caller cannot pile up unlimited handles."""
        steering = [e for e in self._effects if type(e) is type(eff) and not e._finishing()]
        if len(steering) >= MAX_HANDLES_PER_TYPE:
            name = type(eff).__name__
            self._warn(f"handles-{name}", "More than %d live %s handles; ending the oldest", MAX_HANDLES_PER_TYPE,
                       name)
            steering[0]._finish()
        self._effects.append(eff)

    def _add_transient(self, eff: _Effect) -> None:
        self._effects.append(eff)
        transients = [e for e in self._effects if e.transient and e.alive]
        if len(transients) > MAX_TRANSIENT_EFFECTS:
            transients[0]._kill()

    def _add_ring(self, ring: _RingSim) -> None:
        self._rings.append(ring)
        if len(self._rings) > MAX_RINGS:
            self._rings.pop(0)

    def _add_flash(self, intensity: float, center: Vec2 | None, radius: float, duration: float,
                   tint: float) -> None:
        self._flashes.append(_FlashSim(intensity, center, radius, duration, tint))
        if len(self._flashes) > MAX_FLASHES:
            self._flashes.pop(0)

    def _light_pulse(self, pos: Vec2, radius: float, intensity: float, duration: float) -> None:
        self._add_transient(_LightPulse(self, pos, radius, intensity, duration))

    def _flash_color(self, tint: float) -> tuple[float, float, float]:
        """White blended towards the palette's core/inner mix by ``tint`` (0 = pure white)."""
        if tint <= 0.0:
            return (1.0, 1.0, 1.0)
        core, inner = self._palette.core, self._palette.inner
        r, g, b = (1.0 + (0.5 * (c + i) - 1.0) * tint for c, i in zip(core, inner))
        return (float(r), float(g), float(b))

    def _regen_arc(self, slot: _ArcSlot, length_px: float, jaggedness: float = 0.24, branch_prob: float = 0.0,
                   bow: float = 0.0, visible_prob: float = 0.85) -> None:
        """Give an arc slot a fresh bolt shape, flicker state and 40-80 ms lifetime."""
        rng = self.rng
        ss = self.scene_scale
        segs = int(clamp(_finite(length_px, 0.0) / (7.0 * ss), 4.0, 32.0))
        branches: list[np.ndarray] | None = [] if branch_prob > 0.0 else None
        norm = make_bolt((0.0, 0.0), (1.0, 0.0), rng, segs, jaggedness, branch_prob, branches)
        if bow:
            norm[:, 1] += bow * np.sin(np.pi * norm[:, 0])
        slot.norm = norm
        slot.branches = branches or []
        slot.timer = float(rng.uniform(0.04, 0.08))
        slot.visible = bool(rng.random() < visible_prob)
        slot.gain = float(rng.uniform(0.6, 1.0))
        slot.width = float(rng.uniform(1.2, 2.5)) * ss

    def _add_arc(self, out: RenderList, slot: _ArcSlot, a: Vec2, b: Vec2, width: float, intensity: float,
                 glow: float) -> None:
        # Bolt shapes are finite by construction, so finite endpoints make the whole arc finite.
        if not math.isfinite(a[0] + a[1] + b[0] + b[1] + width + intensity + glow):
            return
        if intensity <= 0.0 or math.hypot(b[0] - a[0], b[1] - a[1]) < 2.0:
            return
        pal = self._palette
        out.arcs.append(Arc(points=_place(slot.norm, a, b), width=width, palette=pal, intensity=intensity, glow=glow))
        for br in slot.branches:
            out.arcs.append(Arc(points=_place(br, a, b), width=0.6 * width, palette=pal, intensity=0.6 * intensity,
                                glow=0.8 * glow))

    def _spray(self, shape: int, center: Vec2, n: int, speed: tuple[float, float], *,
               direction: Vec2 | None = None, spread: float = TAU, inner: float = 0.0, even: bool = False,
               size: tuple[float, float] = (1.0, 2.0), size_end: float = 0.5, life: tuple[float, float] = (0.3, 0.6),
               drag: float = 2.5, grav: float = 0.0, intensity: tuple[float, float] = (2.0, 0.3),
               colors: tuple[int, int] = (ROLE_INNER, ROLE_SPARK), mix: tuple[float, float] = (0.35, 1.0),
               fade_in: float = 0.03, flicker: float = 0.0, base_vel: Vec2 | None = None,
               age_spread: float = 0.0, replace: bool = True) -> int:
        """Radial particle spray (sparks, embers, smoke, debris). Returns the number emitted."""
        n = int(n)
        if n <= 0:
            return 0
        n = min(n, self._particles.cap)
        r = self.rng.random((7, n), dtype=np.float32)
        if direction is None:
            if even:
                ang = (np.arange(n, dtype=np.float32) + 0.35 * r[0]) * np.float32(TAU / n)
            else:
                ang = r[0] * np.float32(TAU)
        else:
            ang = math.atan2(direction[1], direction[0]) + (r[0] - 0.5) * spread
        dirs = np.empty((n, 2), np.float32)
        dirs[:, 0] = np.cos(ang)
        dirs[:, 1] = np.sin(ang)
        pos = np.empty((n, 2), np.float32)
        if inner > 0.0:
            rad = inner * (0.55 + 0.45 * r[1])
            pos[:, 0] = center[0] + dirs[:, 0] * rad
            pos[:, 1] = center[1] + dirs[:, 1] * rad
        else:
            pos[:, 0] = center[0]
            pos[:, 1] = center[1]
        spd = speed[0] + (speed[1] - speed[0]) * r[2]
        vel = dirs * spd[:, None]
        if base_vel is not None:
            vel[:, 0] += base_vel[0]
            vel[:, 1] += base_vel[1]
        s0 = size[0] + (size[1] - size[0]) * r[3]
        lf = life[0] + (life[1] - life[0]) * r[4]
        mx = mix[0] + (mix[1] - mix[0]) * r[5]
        age = r[6] * age_spread if age_spread > 0.0 else None
        return self._particles.emit(shape, pos, vel, lf, s0, s0 * size_end, col_a=colors[0], col_b=colors[1],
                                    col_t=mx, int0=intensity[0], int1=intensity[1], drag=drag, grav=grav,
                                    fade_in=fade_in, flicker=flicker, age=age, replace=replace)

    def _emit_gather(self, shape: int, slot: int, center: Vec2, R: float, n: int, charge: float, spin: float,
                     dt: float) -> None:
        """Energy gathering into an orb: particles spawn on a ring at 1.8-3.6 R and spiral in."""
        r = self.rng.random((7, n), dtype=np.float32)
        r0 = 1.8 + 1.8 * r[0]
        theta = r[1] * np.float32(TAU)
        travel = (0.45 + 0.4 * r[2]) * (1.0 - 0.3 * charge)
        # radial speed so that dr/dt = -v / sqrt(r) reaches the absorb radius after ``travel`` s
        v = (2.0 / 3.0) * (r0 ** 1.5 - ABSORB_RADIUS ** 1.5) / travel
        w = spin * (1.2 + 1.6 * r[3]) * np.where(r[4] < 0.88, 1.0, -1.0).astype(np.float32)
        pos = np.empty((n, 2), np.float32)
        pos[:, 0] = center[0] + R * r0 * np.cos(theta)
        pos[:, 1] = center[1] + R * r0 * np.sin(theta)
        ss = self.scene_scale
        orbit = (slot, r0, theta, w, v, 1.0, 1.0, 0.0)
        life = travel * 1.6  # safety margin: they are normally absorbed first
        if shape == _GLOW:
            size0 = np.clip(R * (0.07 + 0.09 * r[5]), 2.5 * ss, 16.0 * ss)
            self._particles.emit(_GLOW, pos, None, life, size0, 0.45 * size0, col_a=ROLE_OUTER, col_b=ROLE_INNER,
                                 col_t=0.35 + 0.65 * r[6], int0=0.45, int1=2.0, fade_in=0.22, orbit=orbit,
                                 replace=False)
        else:
            size0 = (1.0 + 1.3 * r[5]) * ss
            self._particles.emit(_EMBER, pos, None, life, size0, 0.7 * size0, col_a=ROLE_INNER, col_b=ROLE_CORE,
                                 col_t=0.7 * r[6], int0=0.9, int1=2.6, fade_in=0.2, flicker=0.3, orbit=orbit,
                                 replace=False)

    def _emit_orbiters(self, slot: int, center: Vec2, R: float, n: int, spin: float) -> None:
        """Sparks orbiting an orb on tilted ellipses (reads as 3D orbits)."""
        r = self.rng.random((8, n), dtype=np.float32)
        rr = 1.06 + 0.54 * r[0]
        theta = r[1] * np.float32(TAU)
        w = spin * (4.5 + 4.0 * r[2]) * np.where(r[3] < 0.8, 1.0, -1.0).astype(np.float32)
        tilt = 0.18 + 0.82 * r[4]
        rot = r[5] * np.float32(math.pi)
        cr = np.cos(rot)
        sr = np.sin(rot)
        lx = rr * np.cos(theta)
        ly = rr * np.sin(theta) * tilt
        pos = np.empty((n, 2), np.float32)
        pos[:, 0] = center[0] + R * (lx * cr - ly * sr)
        pos[:, 1] = center[1] + R * (lx * sr + ly * cr)
        ss = self.scene_scale
        size0 = (0.9 + 0.7 * r[6]) * ss
        self._particles.emit(_SPARK, pos, None, 0.25 + 0.35 * r[7], size0, 0.6 * size0, col_a=ROLE_SPARK,
                             col_b=ROLE_CORE, col_t=0.2 + 0.7 * r[6], int0=2.2, int1=0.8, fade_in=0.1,
                             orbit=(slot, rr, theta, w, 0.0, tilt, cr, sr), replace=False)

    def _emit_streaks(self, center: Vec2, R: float, n: int, dt: float) -> None:
        """Perspective speed streaks: spawn near the centre, accelerate outward, grow and brighten."""
        ss = self.scene_scale
        r = self.rng.random((7, n), dtype=np.float32)
        ang = r[0] * np.float32(TAU)
        dirs = np.empty((n, 2), np.float32)
        dirs[:, 0] = np.cos(ang)
        dirs[:, 1] = np.sin(ang)
        spawn = R * (0.08 + 0.5 * r[1])
        pos = np.empty((n, 2), np.float32)
        pos[:, 0] = center[0] + dirs[:, 0] * spawn
        pos[:, 1] = center[1] + dirs[:, 1] * spawn
        vel = dirs * ((220.0 + 260.0 * r[2]) * ss)[:, None]
        self._particles.emit(_SPARK, pos, vel, 0.25 + 0.25 * r[4], (0.7 + 0.5 * r[5]) * ss, (2.5 + 2.0 * r[6]) * ss,
                             col_a=ROLE_SPARK, col_b=ROLE_CORE, col_t=r[6], int0=0.35, int1=2.8,
                             drag=-(3.5 + 2.5 * r[3]), fade_in=0.15, age=r[4] * dt, replace=False)

    def _fizzle_particles(self, c: Vec2, R: float, strength: float) -> None:
        ss = self.scene_scale
        dens = self._spark_density
        lo = max(1.5 * R, 80.0 * ss)
        self._spray(_SPARK, c, int(30 * strength * dens), (lo, max(4.0 * R, 1.5 * lo)), inner=0.8 * R,
                    size=(0.8 * ss, 1.6 * ss), life=(0.2, 0.45), drag=4.0, grav=100.0 * ss, intensity=(1.6, 0.2),
                    replace=True)
        smoke = max(6.0 * ss, R)
        self._spray(_SMOKE, c, max(4, int(round(10 * strength))), (10.0 * ss, 50.0 * ss), inner=0.5 * R,
                    size=(0.45 * smoke, 0.8 * smoke), size_end=2.0, life=(0.6, 1.0), drag=1.2, grav=-45.0 * ss,
                    intensity=(0.32, 0.0), colors=(ROLE_SMOKE, ROLE_OUTER), mix=(0.0, 0.35), fade_in=0.25,
                    replace=True)
        self._spray(_EMBER, c, int(14 * strength * dens), (30.0 * ss, 140.0 * ss), inner=0.6 * R,
                    size=(0.9 * ss, 1.8 * ss), life=(0.4, 0.9), drag=1.5, grav=-50.0 * ss, intensity=(1.6, 0.2),
                    colors=(ROLE_INNER, ROLE_CORE), flicker=0.4, replace=True)

    def _output_lights(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        k = clamp(_finite(self._settings.scene_lighting, 1.0), 0.0, 2.0)
        if k <= 0.0 or not lights:
            return
        cand = [lt for lt in lights if lt[3] > 1e-3 and lt[2] > 0.5]
        if not cand:
            return
        cand.sort(key=lambda lt: lt[3], reverse=True)
        color = self._palette.inner
        new = [Light(position=(float(x), float(y)), radius=float(r), color=color, intensity=float(min(i * k, 8.0)))
               for x, y, r, i in cand[:MAX_LIGHTS]]
        if out.lights:
            merged = list(out.lights) + new
            merged.sort(key=lambda lt: lt.intensity, reverse=True)
            out.lights[:] = merged[:MAX_LIGHTS]
        else:
            out.lights.extend(new)

    def _sanitize(self, out: RenderList, marks: dict[str, int]) -> None:
        """Last line of defence: drop primitives that still contain NaN/inf.

        Sprite batches are not re-checked here: particle data is validated when it is
        emitted and non-finite positions are culled every update, so it is finite by
        construction (checking ~3000 particles every frame would cost more than the rest).
        """
        for name, start in marks.items():
            if name == "sprites":
                continue
            lst = getattr(out, name)
            if len(lst) <= start:
                continue
            new = lst[start:]
            good = [p for p in new if _primitive_finite(p)]
            if len(good) != len(new):
                self._warn("nonfinite", "Dropped %d effect primitive(s) with non-finite values", len(new) - len(good))
                del lst[start:]
                lst.extend(good)
        if out.aura is not None and not _primitive_finite(out.aura):
            self._warn("nonfinite-aura", "Dropped an aura with non-finite values")
            out.aura = None
        if not _value_finite(out.shake):
            out.shake = (0.0, 0.0)
        if not _primitive_finite(out.grade):
            out.grade = Grade()
