"""Effect simulation: turns ability requests into backend-neutral render primitives.

The :class:`EffectSystem` simulates every energy effect of the application (ki orb,
Kamehameha beams, ki blasts, energy bursts, shockwaves, flashes, screen shake, colour
grade, scene lights and the power aura) and describes each frame as the primitives of
:mod:`dragon_ball_powers.primitives`. It only *simulates*; the renderers draw.

Design notes
------------
* **Scene space** everywhere: pixels of the mirrored camera frame (x right, y down).
  Effect sizes derive from the radii/widths the abilities pass in and from the *scene
  scale* ``scene_h / 720`` so the look does not depend on the camera resolution.
* **Particles** live in four struct-of-arrays NumPy pools, one per
  :class:`~dragon_ball_powers.primitives.SpriteShape` (column-major ``(fields, N)``
  float32, so integration is a handful of vector operations and compaction of dead
  particles is one gather). The hard cap ``quality.particle_budget ×
  settings.particle_multiplier`` is never exceeded: continuous emitters simply emit
  less when the budget is full, one-shot impacts (bursts, explosions, spark sprays)
  replace the oldest particles instead. Emission rates are additionally scaled by the
  budget relative to the "high" preset, so lower qualities look sparser rather than
  constantly hitting the cap.
* **Gathering particles** use attractors: they move in polar coordinates relative to
  their orb (spiralling inwards, absorbed at 0.35 R), so they stay locked to the orb
  however fast the hands move. Orbiting sparks use the same mechanism on tilted
  elliptical orbits.
* Particle colours are stored as palette **roles** (core / inner / outer / spark /
  white / smoke) and resolved at collect time: switching the energy colour recolours
  everything immediately.
* **Lightning** is generated by vectorised midpoint displacement (:func:`make_bolt`) in
  normalised chord coordinates and mapped onto the current endpoints every frame, so
  arcs stay attached to moving hands between their 40-80 ms re-generations.
* **Determinism**: all randomness comes from ``np.random.default_rng(seed)``; simulation
  time is the sum of the (clamped) ``dt`` values passed to :meth:`EffectSystem.update`
  (``now`` is only recorded). The ``time`` field of each primitive is the age of its
  effect, so shader animation keeps float32 precision however long the app runs; the
  per-effect ``seed`` decorrelates the noise of simultaneous effects.
* **Robustness**: every public input is sanitised (NaN/inf/garbage is ignored with a
  rate-limited warning), each effect is isolated (an exception kills only that effect)
  and a final pass drops any primitive that still contains a non-finite number.

Typical frame (main thread only)::

    abilities.update(...)                 # handle.set...(), effects.burst(...), set_grade(...)
    effects.update(dt, now)
    render_list.clear(); effects.collect(render_list)
    renderer.render(scene, render_list, ui, view)

.. note::
   For speed, arrays inside the collected primitives (sprite batches, aura masks) may be
   **views of internal buffers**. Renderers must consume (upload or copy) them before the
   next :meth:`EffectSystem.update` call and must never modify them.
"""

