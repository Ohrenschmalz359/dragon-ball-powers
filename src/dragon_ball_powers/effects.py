class _Effect:
    """Internal base of every simulated effect (steerable handles and fire-and-forget)."""

    transient = True  # owned by the system (fire-and-forget); handles override with False

    def __init__(self, system: EffectSystem) -> None:
        self._sys = system
        self._alive = True
        self._age = 0.0
        self._seed = float(system.rng.uniform(0.0, 997.0))
        self._acc = [0.0] * 8

    @property
    def alive(self) -> bool:
        """False once the effect has finished; the handle can then be dropped."""
        return self._alive

    def _take(self, i: int, amount: float) -> int:
        """Fractional emission accumulator: returns how many particles to emit now."""
        acc = self._acc[i] + amount
        n = int(acc)
        self._acc[i] = acc - n
        return n

    def _step(self, dt: float) -> None:
        self._age += dt

    def _emit(self, dt: float) -> None:
        pass

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        pass

    def _rescale(self, sx: float, sy: float) -> None:
        pass

    def _quality_changed(self) -> None:
        pass

    def _visible(self) -> bool:
        """Whether the effect currently contributes anything (drives the cinematic grade)."""
        return self._alive

    def _finishing(self) -> bool:
        """True once the effect plays its end animation (no longer steerable)."""
        return not self._alive

    def _finish(self) -> None:
        """Start the graceful end animation (used when too many handles are alive)."""
        self._kill()

    def _kill(self) -> None:
        self._alive = False


