class _RingSim:
    """An expanding shockwave ring (optionally delayed)."""

    __slots__ = ("center", "r0", "r1", "duration", "delay", "thickness", "intensity", "refraction",
                 "noise", "squash", "age", "alive")

    def __init__(self, center: Vec2, r0: float, r1: float, duration: float, thickness: float,
                 intensity: float, refraction: float, noise: float = 0.5, squash: Vec2 = (1.0, 1.0),
                 delay: float = 0.0) -> None:
        self.center = center
        self.r0 = r0
        self.r1 = r1
        self.duration = max(duration, 0.02)
        self.delay = max(delay, 0.0)
        self.thickness = thickness
        self.intensity = intensity
        self.refraction = refraction
        self.noise = noise
        self.squash = squash
        self.age = 0.0
        self.alive = True

    def step(self, dt: float) -> None:
        self.age += dt
        if self.age >= self.delay + self.duration:
            self.alive = False

    def primitive(self, palette: Palette) -> Ring | None:
        t = (self.age - self.delay) / self.duration
        if t < 0.0 or not self.alive:
            return None
        t = min(t, 1.0)
        fade = (1.0 - t) ** 1.5
        return Ring(center=self.center, radius=self.r0 + (self.r1 - self.r0) * ease_out_cubic(t),
                    thickness=max(0.5, self.thickness * (1.0 - 0.7 * t)), palette=palette,
                    intensity=self.intensity * fade, refraction=self.refraction * (1.0 - t) ** 2,
                    noise=self.noise, squash=self.squash, time=max(0.0, self.age - self.delay))

    def rescale(self, sx: float, sy: float) -> None:
        self.center = (self.center[0] * sx, self.center[1] * sy)
        self.r0 *= sy
        self.r1 *= sy
        self.thickness *= sy
        self.refraction *= sy


class _FlashSim:
    """Flash envelope: ~20 ms attack, quadratic decay over ``duration``."""

    ATTACK = 0.02
    __slots__ = ("intensity", "center", "radius", "duration", "tint", "age", "alive")

    def __init__(self, intensity: float, center: Vec2 | None, radius: float, duration: float,
                 tint: float) -> None:
        self.intensity = intensity
        self.center = center
        self.radius = radius
        self.duration = max(duration, 0.02)
        self.tint = tint
        self.age = 0.0
        self.alive = True

    def value(self) -> float:
        t = self.age
        if t < self.ATTACK:
            return self.intensity * (0.35 + 0.65 * t / self.ATTACK)
        u = (t - self.ATTACK) / self.duration
        if u >= 1.0:
            return 0.0
        return self.intensity * (1.0 - u) ** 2

    def step(self, dt: float) -> None:
        self.age += dt
        if self.age >= self.ATTACK + self.duration:
            self.alive = False

    def rescale(self, sx: float, sy: float) -> None:
        if self.center is not None:
            self.center = (self.center[0] * sx, self.center[1] * sy)
        self.radius *= sy


class _Shaker:
    """Camera shake: each shake is a sum of 3 sines per axis under a decaying envelope."""

    MAX_TOTAL = 0.06               # fraction of the scene height (before the user multiplier)
    WEIGHTS = (0.6, 0.28, 0.12)
    RATIOS = (1.0, 1.83, 2.97)

    def __init__(self, rng: np.random.Generator) -> None:
        self.rng = rng
        self.items: list[list[Any]] = []  # [amplitude, duration, age, freqs, phases_x, phases_y]
        self.time = 0.0
        self.sustain_req = 0.0
        self.sustain = 0.0
        self._sus_freq = (13.0, 23.7, 37.3)
        self._sus_px = tuple(float(p) for p in rng.uniform(0.0, TAU, 3))
        self._sus_py = tuple(float(p) for p in rng.uniform(0.0, TAU, 3))

    def add(self, amplitude: float, duration: float) -> None:
        base = float(self.rng.uniform(9.0, 13.0))
        freqs = tuple(base * r * float(self.rng.uniform(0.92, 1.08)) for r in self.RATIOS)
        phx = tuple(float(p) for p in self.rng.uniform(0.0, TAU, 3))
        phy = tuple(float(p) for p in self.rng.uniform(0.0, TAU, 3))
        self.items.append([amplitude, duration, 0.0, freqs, phx, phy])
        if len(self.items) > 16:
            self.items.pop(0)

    def request_sustain(self, amplitude: float) -> None:
        """Continuous shake for this frame (e.g. a roaring beam); max of all requests wins."""
        self.sustain_req = max(self.sustain_req, amplitude)

    def step(self, dt: float) -> None:
        self.time += dt
        for it in self.items:
            it[2] += dt
        self.items = [it for it in self.items if it[2] < it[1]]
        target = self.sustain_req
        self.sustain = damp(self.sustain, target, 14.0 if target > self.sustain else 8.0, dt)
        if target == 0.0 and self.sustain < 2e-5:
            self.sustain = 0.0
        self.sustain_req = 0.0

    @property
    def active(self) -> bool:
        return bool(self.items) or self.sustain > 0.0

    def clear(self) -> None:
        self.items.clear()
        self.sustain = 0.0
        self.sustain_req = 0.0

    def offset(self, scene_h: float, multiplier: float) -> Vec2:
        if multiplier <= 0.0 or not self.active:
            return (0.0, 0.0)
        x = y = 0.0
        for amp, duration, age, freqs, phx, phy in self.items:
            env = amp * (1.0 - age / duration) ** 2
            sx = sy = 0.0
            for w, f, px, py in zip(self.WEIGHTS, freqs, phx, phy):
                arg = TAU * f * age
                sx += w * math.sin(arg + px)
                sy += w * math.sin(arg + py)
            x += env * sx
            y += env * sy
        if self.sustain > 0.0:
            t = self.time
            for w, f, px, py in zip(self.WEIGHTS, self._sus_freq, self._sus_px, self._sus_py):
                arg = TAU * f * t
                x += self.sustain * w * math.sin(arg + px)
                y += self.sustain * w * math.sin(arg + py)
        mag = math.hypot(x, y)
        if mag > self.MAX_TOTAL:  # stacked shakes are clamped
            k = self.MAX_TOTAL / mag
            x *= k
            y *= k
        s = scene_h * multiplier
        return (x * s, y * s)


class _GradeState:
    """Smoothed cinematic colour grade (darken, desaturate, vignette, impact pulses)."""

    RISE = 6.0
    FALL = 3.0
    EPS = 2e-3

    def __init__(self) -> None:
        self.reset()

    def reset(self) -> None:
        self.req_darken = 0.0
        self.req_desat = 0.0
        self.requested = False
        self.darken = 0.0
        self.desat = 0.0
        self.activity = 0.0
        self.chroma = 0.0
        self.zoom = 0.0

    def request(self, darken: float, desat: float) -> None:
        if darken <= 0.0 and desat <= 0.0:
            return
        self.req_darken = max(self.req_darken, darken)
        self.req_desat = max(self.req_desat, desat)
        self.requested = True

    def pulse(self, chroma_px: float, zoom: float) -> None:
        self.chroma = max(self.chroma, chroma_px)
        self.zoom = max(self.zoom, zoom)

    @classmethod
    def _approach(cls, cur: float, target: float, dt: float) -> float:
        return damp(cur, target, cls.RISE if target > cur else cls.FALL, dt)

    def step(self, dt: float, running: bool) -> None:
        self.darken = self._approach(self.darken, self.req_darken, dt)
        self.desat = self._approach(self.desat, self.req_desat, dt)
        busy = self.requested or running
        self.activity = self._approach(self.activity, 1.0 if busy else 0.0, dt)
        if dt > 0.0:
            self.chroma *= math.exp(-7.0 * dt)
            self.zoom *= math.exp(-5.0 * dt)
        if not self.requested:
            if self.darken < self.EPS:
                self.darken = 0.0
            if self.desat < self.EPS:
                self.desat = 0.0
        if not busy and self.activity < self.EPS:
            self.activity = 0.0
        if self.chroma < 0.01:
            self.chroma = 0.0
        if self.zoom < 1e-4:
            self.zoom = 0.0
        self.req_darken = 0.0
        self.req_desat = 0.0
        self.requested = False

    @property
    def identity(self) -> bool:
        return (self.darken == 0.0 and self.desat == 0.0 and self.activity == 0.0
                and self.chroma == 0.0 and self.zoom == 0.0)

    def output(self, settings: EffectsSettings, palette: Palette, scene_scale: float) -> Grade:
        if self.identity:
            return Grade()
        cd = clamp(_finite(settings.camera_darken, 0.45))
        rel = clamp(cd / 0.45)  # desaturation / tint follow the user's darkening preference
        d = self.darken
        return Grade(
            darken=clamp(d * cd),
            desaturate=min(0.4, self.desat * rel),
            tint=palette.inner,
            tint_strength=clamp(0.12 * d * rel),
            vignette=clamp(0.15 * self.activity + 0.35 * d),
            chromatic=min(3.0 * scene_scale, self.chroma),
            zoom=1.0 + min(0.03, self.zoom),
        )


