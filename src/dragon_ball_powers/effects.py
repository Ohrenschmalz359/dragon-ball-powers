class OrbEffect(_Effect):
    """A charging ki orb steered by an ability every tick (create with :meth:`EffectSystem.create_orb`).

    Read-only state: ``alive``, ``center`` (smoothed), ``radius`` (smoothed, without the
    pulse), ``charge``. Call :meth:`set_target` every tick while charging, then either
    :meth:`release` (the energy is consumed by an attack) or :meth:`dissipate` (cancelled).
    Milestone pulses (25/50/75/100 %) are produced here automatically.
    """

    transient = False
    CENTER_RATE = 40.0       # 1/s: the orb must stay between the hands
    RADIUS_RATE = 12.0
    VELOCITY_RATE = 20.0
    RELEASE_TIME = 0.12
    DISSIPATE_TIME = 0.35
    TRAIL_TIME = 0.25
    MILESTONES = (0.25, 0.5, 0.75, 1.0)

    def __init__(self, system: EffectSystem, center: Vec2, radius: float) -> None:
        super().__init__(system)
        self._center: Vec2 = center
        self._target: Vec2 = center
        self._target_radius = radius
        self._radius = 0.4 * radius      # ignites small and swells to the target radius
        self._charge = 0.0
        self._left: Vec2 | None = None
        self._right: Vec2 | None = None
        self._vel: Vec2 = (0.0, 0.0)
        self._mode = _ACTIVE
        self._mode_age = 0.0
        self._milestone = 0
        self._boost = 0.0
        self._spin = 1.0 if system.rng.random() < 0.5 else -1.0
        self._slot = system._particles.acquire_attractor()
        self._hand_arcs: tuple[list[_ArcSlot], list[_ArcSlot]] = ([], [])
        self._crawl_arcs: list[_ArcSlot] = []
        self._trail: deque[tuple[float, float, float, float]] = deque()
        self._disp_radius = self._radius
        self._disp_intensity = 1.1
        self._light_gain = 1.0
        self._update_display()
        if self._slot >= 0:
            system._particles.set_attractor(self._slot, center, self._disp_radius, 1.0)
        # ignition: a small pop of light and sparks (orbs usually start tiny and swell with the
        # charge, so the pop is sized at least for a modest orb)
        ss = system.scene_scale
        pop = max(radius, 20.0 * ss)
        system.flash(0.25, center=center, radius=3.0 * pop, duration=0.12)
        system._spray(_SPARK, center, int(14 * system._spark_density), (2.0 * pop, 5.0 * pop),
                      inner=0.5 * radius, size=(0.8 * ss, 1.5 * ss), life=(0.15, 0.35), drag=4.0,
                      intensity=(2.0, 0.3), replace=False)

    # ----------------------------------------------------------------- public

    @property
    def center(self) -> Vec2:
        return self._center

    @property
    def radius(self) -> float:
        return self._radius

    @property
    def charge(self) -> float:
        return self._charge

    @property
    def velocity(self) -> Vec2:
        """Smoothed orb velocity in px/s."""
        return self._vel

    def set_target(self, center: Vec2, radius: float, charge: float, left_hand: Vec2 | None = None,
                   right_hand: Vec2 | None = None) -> None:
        """Steer the orb: target centre/radius (scene px), charge 0..1 and the hand anchors for arcs."""
        if not self._alive or self._mode != _ACTIVE:
            return
        sys = self._sys
        c = sys._vec(center, "orb center")
        if c is not None:
            self._target = sys._clamp_pos(c)
        r = _finite(radius, -1.0)
        if r > 0.0:
            self._target_radius = sys._len_value(r, self._target_radius)
        self._charge = clamp(_finite(charge, self._charge))
        left = sys._vec(left_hand, "orb left hand")
        right = sys._vec(right_hand, "orb right hand")
        self._left = sys._clamp_pos(left) if left is not None else None
        self._right = sys._clamp_pos(right) if right is not None else None

    def release(self) -> None:
        """The energy is consumed by an attack: bright collapse (0.12 s), then dead."""
        if not self._alive or self._mode != _ACTIVE:
            return
        self._mode = _RELEASING
        self._mode_age = 0.0
        if self._slot >= 0:  # gathered energy rushes into the core
            self._sys._particles.set_attractor(self._slot, self._center, self._disp_radius, 5.0)
        for slots in self._hand_arcs:
            slots.clear()

    def dissipate(self) -> None:
        """Cancelled charge: fizzle out (0.35 s: shrink, flicker, spark scatter, smoke), then dead.

        Includes the fizzle particles, so abilities need not call :meth:`EffectSystem.fizzle` too.
        """
        if not self._alive or self._mode != _ACTIVE:
            return
        sys = self._sys
        self._mode = _DISSIPATING
        self._mode_age = 0.0
        if self._slot >= 0:
            sys._particles.release_attractor(self._slot, life_left=0.35, kick=2.5 * self._disp_radius)
            self._slot = -1
        for slots in self._hand_arcs:
            slots.clear()
        sys._fizzle_particles(self._center, self._disp_radius, 0.6 + 0.4 * self._charge)

    # ------------------------------------------------------------- simulation

    def _step(self, dt: float) -> None:
        super()._step(dt)
        prev = self._center
        if self._mode == _ACTIVE:
            self._center = damp_vec(self._center, self._target, self.CENTER_RATE, dt)
            self._radius = damp(self._radius, self._target_radius, self.RADIUS_RATE, dt)
            self._update_milestones()
        else:
            self._mode_age += dt
            limit = self.RELEASE_TIME if self._mode == _RELEASING else self.DISSIPATE_TIME
            if self._mode_age >= limit:
                self._kill()
                return
        if dt > 0.0:
            inst = ((self._center[0] - prev[0]) / dt, (self._center[1] - prev[1]) / dt)
            self._vel = damp_vec(self._vel, inst, self.VELOCITY_RATE, dt)
            self._boost *= math.exp(-5.0 * dt)
        self._update_display()
        if self._slot >= 0:
            self._sys._particles.set_attractor(self._slot, self._center, self._disp_radius)
        self._record_trail()
        self._update_arcs(dt)

    def _update_display(self) -> None:
        sys = self._sys
        c = self._charge
        pulse = 1.0 + 0.04 * math.sin(TAU * 3.0 * self._age + self._seed)
        radius = self._radius * (1.0 + 0.06 * self._boost)
        intensity = (1.1 + 0.9 * c) * pulse + 0.6 * self._boost
        light = pulse + 0.5 * self._boost
        if self._mode == _RELEASING:
            e = ease_out_cubic(self._mode_age / self.RELEASE_TIME)
            radius *= lerp(1.0, 0.6, e)
            intensity *= lerp(1.0, 2.0, e)
            light *= lerp(1.0, 2.0, e)
        elif self._mode == _DISSIPATING:
            u = clamp(self._mode_age / self.DISSIPATE_TIME)
            flicker = float(sys.rng.uniform(0.45, 1.0))
            radius *= lerp(1.0, 0.25, u)
            intensity *= (1.0 - u) * flicker
            light *= (1.0 - u) * flicker
        self._disp_radius = max(radius, 0.5)
        self._disp_intensity = intensity
        self._light_gain = light

    def _update_milestones(self) -> None:
        c = self._charge
        top = -1
        while self._milestone < len(self.MILESTONES) and c >= self.MILESTONES[self._milestone] - 1e-3:
            top = self._milestone
            self._milestone += 1
        if top >= 0:  # a jump over several milestones produces one (the biggest) pulse
            self._milestone_pulse(self.MILESTONES[top])
        while self._milestone > 0 and c < self.MILESTONES[self._milestone - 1] - 0.15:
            self._milestone -= 1  # hysteresis: a recharge may trigger the milestone again

    def _milestone_pulse(self, level: float) -> None:
        sys = self._sys
        R = max(self._radius, 2.0)
        c = self._center
        ss = sys.scene_scale
        sys.shockwave(c, R, level)
        sys.flash(0.25 + 0.5 * level, center=c, radius=4.0 * R, duration=0.18)
        n = int((20 + 28 * level) * sys._spark_density)
        sys._spray(_SPARK, c, n, ((3.0 + 3.0 * level) * R, (4.5 + 4.5 * level) * R), inner=R, even=True,
                   size=(1.0 * ss, 1.9 * ss), life=(0.3, 0.5), drag=4.0, intensity=(2.4, 0.3), replace=True)
        sys.shake(0.003 + 0.007 * level, 0.25)
        sys._light_pulse(c, 8.0 * R, 1.2 * level, 0.3)
        self._boost = 1.0

    def _record_trail(self) -> None:
        t = self._sys.time
        tr = self._trail
        tr.append((t, self._center[0], self._center[1], self._disp_radius))
        while len(tr) > 2 and t - tr[0][0] > self.TRAIL_TIME:
            tr.popleft()
        while len(tr) > 96:
            tr.popleft()

    def _fast_factor(self) -> float:
        speed = math.hypot(self._vel[0], self._vel[1])
        thresh = max(3.0 * self._disp_radius, 250.0 * self._sys.scene_scale)
        return smoothstep(thresh, 2.5 * thresh, speed)

    def _update_arcs(self, dt: float) -> None:
        sys = self._sys
        rng = sys.rng
        q = max(0, int(sys._quality.arc_count))
        R = self._disp_radius
        c = self._charge
        cx, cy = self._center
        n_hand = min(q, 1 + int(round((q - 1) * c))) if (self._mode == _ACTIVE and q > 0) else 0
        for side, hand in enumerate((self._left, self._right)):
            slots = self._hand_arcs[side]
            dist = math.hypot(hand[0] - cx, hand[1] - cy) if hand is not None else 0.0
            want = n_hand if (hand is not None and dist > R) else 0   # inside the orb an arc is hidden
            del slots[want:]
            while len(slots) < want:
                slots.append(_ArcSlot())
            for k, slot in enumerate(slots):
                slot.timer -= dt
                if slot.timer <= 0.0:
                    slot.p0 = float(rng.uniform(-0.55, 0.55))    # start angle offset on the surface
                    if k == 0:
                        slot.p1 = slot.p2 = 0.0                  # the first bolt hits the anchor exactly
                    else:
                        ang = float(rng.uniform(0.0, TAU))
                        rad = float(rng.uniform(0.05, 0.3))      # jitter around the hand, x R
                        slot.p1 = math.cos(ang) * rad
                        slot.p2 = math.sin(ang) * rad
                    sys._regen_arc(slot, dist - R, jaggedness=0.24, branch_prob=0.12 * c)
        if q > 0 and self._mode == _DISSIPATING:
            n_crawl = min(q, 2)
        elif q > 0 and self._mode == _ACTIVE and c > 0.5:
            n_crawl = min(q, 1 + int((c - 0.5) / 0.5 * max(1, q // 2)))
        else:
            n_crawl = 0
        del self._crawl_arcs[n_crawl:]
        while len(self._crawl_arcs) < n_crawl:
            self._crawl_arcs.append(_ArcSlot())
        for slot in self._crawl_arcs:
            slot.timer -= dt
            if slot.timer <= 0.0:
                slot.p0 = float(rng.uniform(0.0, TAU))
                slot.p1 = float(rng.uniform(0.5, 1.3))
                chord = 2.0 * R * math.sin(0.5 * slot.p1)
                sys._regen_arc(slot, chord, jaggedness=0.3, bow=-0.22, visible_prob=0.8)
                slot.width *= 0.8

    def _emit(self, dt: float) -> None:
        if dt <= 0.0:
            return
        sys = self._sys
        ss = sys.scene_scale
        R = self._disp_radius
        c = self._charge
        ctr = self._center
        dens = sys._density * clamp(R / (60.0 * ss), 0.6, 1.8)
        if self._mode == _ACTIVE:
            gather = (0.3 + c) * dens * dt
            if self._slot >= 0:
                n = self._take(0, 110.0 * gather)
                if n:
                    sys._emit_gather(_GLOW, self._slot, ctr, R, n, c, self._spin, dt)
                n = self._take(1, 200.0 * gather)
                if n:
                    sys._emit_gather(_EMBER, self._slot, ctr, R, n, c, self._spin, dt)
                n = self._take(2, 60.0 * gather)
                if n:
                    sys._emit_orbiters(self._slot, ctr, R, n, self._spin)
            eject = smoothstep(0.6, 1.0, c)
            if eject > 0.0:
                n = self._take(3, 110.0 * eject * dens * dt)
                if n:
                    lo = max(2.5 * R, 150.0 * ss)
                    sys._spray(_SPARK, ctr, n, (lo, max(6.0 * R, 1.6 * lo)), inner=R, size=(0.9 * ss, 1.8 * ss),
                               life=(0.2, 0.45), drag=3.0, intensity=(2.5, 0.6), age_spread=dt, replace=False)
            fast = self._fast_factor()
            if fast > 0.0 and sys._settings.motion_trails:
                n = self._take(4, 160.0 * fast * dens * dt)
                if n:
                    base = (0.3 * self._vel[0], 0.3 * self._vel[1])
                    sys._spray(_SPARK, ctr, n, (20.0 * ss, 90.0 * ss), inner=0.9 * R, base_vel=base,
                               size=(0.9 * ss, 1.6 * ss), life=(0.12, 0.3), drag=4.0, intensity=(2.2, 0.4),
                               age_spread=dt, replace=False)
        elif self._mode == _DISSIPATING:
            u = clamp(self._mode_age / self.DISSIPATE_TIME)
            n = self._take(5, 140.0 * (1.0 - u) * dens * dt)
            if n:
                sys._spray(_SPARK, ctr, n, (1.5 * R, 4.0 * R), inner=0.9 * R, size=(0.8 * ss, 1.5 * ss),
                           life=(0.15, 0.35), drag=4.0, grav=100.0 * ss, intensity=(1.6, 0.2),
                           age_spread=dt, replace=False)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        sys = self._sys
        pal = sys._palette
        c = self._charge
        R = self._disp_radius
        vx, vy = self._vel
        speed = math.hypot(vx, vy)
        stretch = min(0.25, 0.25 * speed / max(10.0 * R, 1.0))
        squash = (1.0 + stretch, 1.0 / math.sqrt(1.0 + stretch))
        rotation = math.atan2(vy, vx) if speed > 1e-3 else 0.0
        instability = c * c
        flare = smoothstep(0.6, 1.0, c)
        if self._mode == _RELEASING:
            flare = max(flare, ease_out_cubic(self._mode_age / self.RELEASE_TIME))
        elif self._mode == _DISSIPATING:
            instability = max(instability, 0.5 + 0.5 * clamp(self._mode_age / self.DISSIPATE_TIME))
            flare = 0.0
        out.orbs.append(Orb(center=self._center, radius=R, palette=pal, intensity=self._disp_intensity,
                            charge=c, time=self._age, seed=self._seed, swirl=1.0 + c, instability=instability,
                            flare=flare, squash=squash, rotation=rotation))
        self._collect_arcs(out)
        if sys._settings.motion_trails:
            self._collect_trail(out, pal)
        lights.append((self._center[0], self._center[1], 6.0 * R, (0.6 + 1.4 * c) * self._light_gain))

    def _collect_arcs(self, out: RenderList) -> None:
        sys = self._sys
        c = self._charge
        R = self._disp_radius
        cx, cy = self._center
        for hand, slots in ((self._left, self._hand_arcs[0]), (self._right, self._hand_arcs[1])):
            if hand is None or not slots:
                continue
            base = math.atan2(hand[1] - cy, hand[0] - cx)
            for slot in slots:
                if not slot.visible:
                    continue
                ang = base + slot.p0
                a = (cx + math.cos(ang) * R * 0.92, cy + math.sin(ang) * R * 0.92)
                b = (hand[0] + slot.p1 * R, hand[1] + slot.p2 * R)
                sys._add_arc(out, slot, a, b, slot.width * (0.8 + 0.4 * c), (1.2 + 1.3 * c) * slot.gain,
                             1.0 + 0.5 * c)
        for slot in self._crawl_arcs:
            if not slot.visible:
                continue
            a1 = slot.p0
            a2 = slot.p0 + slot.p1
            a = (cx + math.cos(a1) * R, cy + math.sin(a1) * R)
            b = (cx + math.cos(a2) * R, cy + math.sin(a2) * R)
            sys._add_arc(out, slot, a, b, slot.width, (1.0 + 1.2 * c) * slot.gain, 1.2)

    def _collect_trail(self, out: RenderList, pal: Palette) -> None:
        fast = self._fast_factor()
        if fast <= 0.02 or len(self._trail) < 3:
            return
        arr = np.asarray(self._trail, dtype=np.float64)   # float64: the clock grows all session
        t0 = float(arr[0, 0])
        span = max(float(arr[-1, 0]) - t0, 1e-6)
        s = (arr[:, 0] - t0) / span
        pts = arr[:, 1:3].astype(np.float32)
        widths = (arr[:, 3] * (0.25 + 0.65 * s)).astype(np.float32)
        intens = (fast * (0.4 + 0.6 * self._charge) * 1.3 * s ** 1.5).astype(np.float32)
        out.ribbons.append(Ribbon(points=pts, widths=widths, intensities=intens, palette=pal))

    def _finishing(self) -> bool:
        return not self._alive or self._mode != _ACTIVE

    def _finish(self) -> None:
        self.dissipate()

    def _rescale(self, sx: float, sy: float) -> None:
        self._center = (self._center[0] * sx, self._center[1] * sy)
        self._target = (self._target[0] * sx, self._target[1] * sy)
        self._vel = (self._vel[0] * sx, self._vel[1] * sy)
        self._radius *= sy
        self._target_radius *= sy
        self._disp_radius *= sy
        if self._left is not None:
            self._left = (self._left[0] * sx, self._left[1] * sy)
        if self._right is not None:
            self._right = (self._right[0] * sx, self._right[1] * sy)
        self._trail.clear()

    def _kill(self) -> None:
        if self._slot >= 0:
            self._sys._particles.release_attractor(self._slot, life_left=0.1)
            self._slot = -1
        for slots in self._hand_arcs:
            slots.clear()
        self._crawl_arcs.clear()
        super()._kill()


# ------------------------------------------------------------------ lateral beam


class BeamEffect(_Effect):
    """A lateral Kamehameha beam (create with :meth:`EffectSystem.create_beam`).

    Read-only state: ``alive``, ``progress`` (0..1 extension towards the scene edge),
    ``origin``, ``direction``, ``length``, ``power``. Steer it every tick with :meth:`set`;
    :meth:`end` lets it dissipate (0.5 s) and die.
    """

    transient = False
    EXTEND_TIME = 0.15
    END_TIME = 0.5
    ORIGIN_RATE = 30.0
    TURN_RATE = 14.0          # 1/s exponential approach of the aim ...
    MAX_TURN_SPEED = 3.5      # ... limited to this angular speed (rad/s)
    POWER_RATE = 8.0
    RING_INTERVAL = 0.25
    RING_LIFE = 0.6
    PERSPECTIVE = 0.32

    def __init__(self, system: EffectSystem, origin: Vec2, direction: Vec2, width: float, power: float) -> None:
        super().__init__(system)
        self._origin: Vec2 = origin
        self._target_origin: Vec2 = origin
        self._angle = math.atan2(direction[1], direction[0])
        self._target_angle = self._angle
        self._base_width = width
        self._power = power
        self._target_power = power
        self._progress = 0.0
        self._ending = False
        self._end_age = 0.0
        self._exit = 0.0
        self._full_length = 0.0
        self._length = 0.0
        self._visible = 0.0
        self._ring_timer = 0.05
        self._rings: list[list[float]] = []   # [distance along the beam, age]
        q = max(0, int(system._quality.arc_count))
        self._arcs = [_ArcSlot() for _ in range(min(3, max(2, q // 2)) if q > 0 else 0)]
        self._update_geometry()
        self._release_burst()

    # ----------------------------------------------------------------- public

    @property
    def progress(self) -> float:
        return self._progress

    @property
    def origin(self) -> Vec2:
        return self._origin

    @property
    def direction(self) -> Vec2:
        return (math.cos(self._angle), math.sin(self._angle))

    @property
    def length(self) -> float:
        return self._length

    @property
    def power(self) -> float:
        return self._power

    def set(self, origin: Vec2, direction: Vec2, power: float | None = None) -> None:
        """Steer the beam: origin (smoothed), direction (rate limited), optional power 0..1."""
        if not self._alive or self._ending:
            return
        sys = self._sys
        o = sys._vec(origin, "beam origin")
        if o is not None:
            self._target_origin = sys._clamp_pos(o)
        d = _unit(sys._vec(direction, "beam direction"))
        if d is not None:
            self._target_angle = math.atan2(d[1], d[0])
        if power is not None:
            self._target_power = sys._power_value(power, self._target_power)

    def end(self) -> None:
        """Stop firing: the beam breaks up into wisps over 0.5 s, then dies."""
        if self._alive and not self._ending:
            self._ending = True
            self._end_age = 0.0

    # ------------------------------------------------------------- simulation

    def _end_fraction(self) -> float:
        return clamp(self._end_age / self.END_TIME) if self._ending else 0.0

    def _width_now(self) -> float:
        w = self._base_width * (0.75 + 0.5 * min(self._power, 1.5))
        w *= 1.0 + 0.05 * math.sin(TAU * 7.0 * self._age + self._seed)
        if self._ending:
            w *= 1.0 - 0.5 * self._end_fraction()
        return max(w, 0.5)

    def _update_geometry(self) -> None:
        sys = self._sys
        self._exit = _ray_exit(self._origin, self.direction, sys._scene_w, sys._scene_h)
        self._full_length = self._exit + 0.25 * sys._scene_w
        self._length = self._progress * self._full_length
        self._visible = min(self._length, self._exit)

    def _release_burst(self) -> None:
        sys = self._sys
        ss = sys.scene_scale
        h = sys._scene_h
        p = self._power
        p1 = min(p, 1.0)
        o = self._origin
        w = self._width_now()
        sys.flash(1.0 + 0.8 * p, center=o, radius=max(0.5 * h, 10.0 * w), duration=0.3)
        sys.shockwave(o, max(1.4 * w, 8.0 * ss), 0.5 + 0.4 * p1)
        n = int((60 + 120 * p1) * sys._spark_density)
        sys._spray(_SPARK, o, n, (500.0 * ss, 1500.0 * ss), direction=self.direction, spread=1.8, inner=0.6 * w,
                   size=(1.0 * ss, 2.2 * ss), life=(0.2, 0.5), drag=3.0, intensity=(2.4, 0.4), replace=True)
        sys._spray(_SPARK, o, n // 2, (250.0 * ss, 800.0 * ss), inner=0.5 * w, size=(0.9 * ss, 1.8 * ss),
                   life=(0.2, 0.45), drag=3.5, intensity=(2.0, 0.3), replace=True)
        sys.shake(0.02 * p, 0.4)
        sys._grade.pulse(2.0 * ss * p1, 0.012 * p1)
        sys._light_pulse(o, max(10.0 * w, 0.5 * h), 1.5 + p, 0.35)

    def _step(self, dt: float) -> None:
        super()._step(dt)
        sys = self._sys
        if self._ending:
            self._end_age += dt
            if self._end_age >= self.END_TIME:
                self._kill()
                return
        else:
            self._origin = damp_vec(self._origin, self._target_origin, self.ORIGIN_RATE, dt)
            if dt > 0.0:
                delta = _wrap_angle(self._target_angle - self._angle)
                step = delta * (1.0 - math.exp(-self.TURN_RATE * dt))
                max_step = self.MAX_TURN_SPEED * dt
                self._angle = _wrap_angle(self._angle + clamp(step, -max_step, max_step))
            self._power = damp(self._power, self._target_power, self.POWER_RATE, dt)
            self._progress = ease_out_cubic(self._age / self.EXTEND_TIME)
            sys._shaker.request_sustain(0.004 * (0.6 + 0.4 * min(self._power, 1.0)))
        self._update_geometry()
        width = self._width_now()
        # rings travelling outward along the beam
        if not self._ending:
            self._ring_timer -= dt
            if self._ring_timer <= 0.0:
                self._ring_timer = self.RING_INTERVAL * float(sys.rng.uniform(0.8, 1.2))
                self._rings.append([0.3 * width, 0.0])
        speed = 0.85 * sys._scene_w * (0.8 + 0.3 * min(self._power, 1.0))
        for ring in self._rings:
            ring[0] += speed * dt
            ring[1] += dt
        limit = self._length + width
        self._rings = [r for r in self._rings if r[1] < self.RING_LIFE and r[0] < limit]
        # arcs crawling along the beam edges
        if not self._ending:
            rng = sys.rng
            for slot in self._arcs:
                slot.timer -= dt
                if slot.timer <= 0.0:
                    slot.p0 = float(rng.uniform(0.02, 0.55))
                    slot.p1 = float(rng.uniform(0.12, 0.3))
                    slot.p2 = 1.0 if rng.random() < 0.5 else -1.0
                    slot.p3 = float(rng.uniform(0.8, 1.15))
                    sys._regen_arc(slot, slot.p1 * max(self._exit, 1.0), jaggedness=0.2, branch_prob=0.08,
                                   visible_prob=0.8)

    def _emit(self, dt: float) -> None:
        if dt <= 0.0:
            return
        sys = self._sys
        rng = sys.rng
        ss = sys.scene_scale
        dens = sys._density
        L = self._visible
        if L < 2.0:
            return
        width = self._width_now()
        p1 = min(self._power, 1.0)
        dx, dy = self.direction
        nx, ny = -dy, dx
        ox, oy = self._origin
        if not self._ending:
            cover = min(1.0, L / (0.5 * sys._scene_w))
            # bright sparks streaming along the beam
            n = self._take(0, 280.0 * dens * (0.6 + 0.4 * p1) * cover * dt)
            if n:
                r = rng.random((7, n), dtype=np.float32)
                s = r[0] * L
                off = (r[1] * 2.0 - 1.0) * width * 0.9
                pos = np.empty((n, 2), np.float32)
                pos[:, 0] = ox + dx * s + nx * off
                pos[:, 1] = oy + dy * s + ny * off
                spd = sys._scene_w * (0.9 + 0.8 * r[2])
                side = (r[3] * 2.0 - 1.0) * 60.0 * ss
                vel = np.empty((n, 2), np.float32)
                vel[:, 0] = dx * spd + nx * side
                vel[:, 1] = dy * spd + ny * side
                size0 = (0.9 + 0.8 * r[4]) * ss * clamp(math.sqrt(width / (20.0 * ss)), 0.7, 1.8)
                sys._particles.emit(_SPARK, pos, vel, 0.08 + 0.14 * r[5], size0, 0.6 * size0, col_a=ROLE_SPARK,
                                    col_b=ROLE_CORE, col_t=r[6], int0=2.2, int1=1.0, fade_in=0.04,
                                    age=r[5] * dt, replace=False)
            # soft energy blobs flowing with the beam
            n = self._take(1, 140.0 * dens * cover * dt)
            if n:
                r = rng.random((6, n), dtype=np.float32)
                s = r[0] * L
                off = (r[1] * 2.0 - 1.0) * width * 0.6
                pos = np.empty((n, 2), np.float32)
                pos[:, 0] = ox + dx * s + nx * off
                pos[:, 1] = oy + dy * s + ny * off
                spd = sys._scene_w * (0.4 + 0.5 * r[2])
                vel = np.empty((n, 2), np.float32)
                vel[:, 0] = dx * spd
                vel[:, 1] = dy * spd
                size0 = (0.35 + 0.35 * r[3]) * width
                sys._particles.emit(_GLOW, pos, vel, 0.15 + 0.2 * r[4], size0, 0.7 * size0, col_a=ROLE_OUTER,
                                    col_b=ROLE_INNER, col_t=r[5], int0=0.45, int1=0.05, fade_in=0.15,
                                    age=r[4] * dt, replace=False)
            # sparks peeling off the edges
            n = self._take(2, 70.0 * dens * cover * dt)
            if n:
                r = rng.random((6, n), dtype=np.float32)
                s = r[0] * L
                sgn = np.where(r[1] < 0.5, -1.0, 1.0).astype(np.float32)
                pos = np.empty((n, 2), np.float32)
                pos[:, 0] = ox + dx * s + nx * sgn * width
                pos[:, 1] = oy + dy * s + ny * sgn * width
                out_spd = (80.0 + 180.0 * r[2]) * ss * sgn
                fwd = (200.0 + 400.0 * r[3]) * ss
                vel = np.empty((n, 2), np.float32)
                vel[:, 0] = nx * out_spd + dx * fwd
                vel[:, 1] = ny * out_spd + dy * fwd
                size0 = (0.8 + 0.6 * r[4]) * ss
                sys._particles.emit(_SPARK, pos, vel, 0.15 + 0.15 * r[5], size0, 0.5 * size0, col_a=ROLE_SPARK,
                                    col_b=ROLE_CORE, col_t=r[4], int0=2.0, int1=0.3, drag=4.0, fade_in=0.04,
                                    age=r[5] * dt, replace=False)
            # spray at the head while it is on screen
            hx = ox + dx * self._length
            hy = oy + dy * self._length
            if 0.0 <= hx <= sys._scene_w and 0.0 <= hy <= sys._scene_h:
                n = self._take(3, 400.0 * dens * dt)
                if n:
                    sys._spray(_SPARK, (hx, hy), n, (300.0 * ss, 900.0 * ss), direction=(dx, dy), spread=2.4,
                               inner=1.2 * width, size=(1.0 * ss, 2.0 * ss), life=(0.15, 0.35), drag=3.0,
                               intensity=(2.4, 0.3), age_spread=dt, replace=False)
        else:
            u = self._end_fraction()
            n = self._take(4, 420.0 * dens * (1.0 - u) * dt)
            if n:
                r = rng.random((6, n), dtype=np.float32)
                s = r[0] * L
                off = (r[1] * 2.0 - 1.0) * width
                pos = np.empty((n, 2), np.float32)
                pos[:, 0] = ox + dx * s + nx * off
                pos[:, 1] = oy + dy * s + ny * off
                drift = (r[2] * 2.0 - 1.0) * (40.0 + 120.0 * r[3]) * ss
                fwd = (50.0 + 150.0 * r[4]) * ss
                vel = np.empty((n, 2), np.float32)
                vel[:, 0] = nx * drift + dx * fwd
                vel[:, 1] = ny * drift + dy * fwd - 30.0 * ss
                size0 = (0.5 + 0.7 * r[5]) * width
                half = n // 2
                sys._particles.emit(_SMOKE, pos[:half], vel[:half], 0.3 + 0.3 * r[3, :half], size0[:half],
                                    1.8 * size0[:half], col_a=ROLE_SMOKE, col_b=ROLE_INNER, col_t=r[2, :half],
                                    int0=0.3, int1=0.0, drag=1.5, fade_in=0.2, replace=False)
                sys._particles.emit(_GLOW, pos[half:], vel[half:], 0.25 + 0.3 * r[3, half:], 0.5 * size0[half:],
                                    0.2 * size0[half:], col_a=ROLE_OUTER, col_b=ROLE_INNER, col_t=r[2, half:],
                                    int0=0.6, int1=0.0, drag=2.0, fade_in=0.1, replace=False)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        sys = self._sys
        pal = sys._palette
        ss = sys.scene_scale
        u = self._end_fraction()
        fade = 1.0 - u
        width = self._width_now()
        end_width = 1.35 * width
        p = self._power
        p1 = min(p, 1.0)
        d = self.direction
        o = self._origin
        L = self._length
        out.beams.append(Beam(origin=o, direction=d, length=L, width=width, end_width=end_width, palette=pal,
                              intensity=1.6 + p, time=self._age, seed=self._seed,
                              head_radius=1.6 * width * (1.0 - u), turbulence=0.8 + 0.5 * p1 + 0.8 * u,
                              flow_speed=1.0 + p, fade=fade, dissolve=u))
        squash = _perspective_squash(d, self.PERSPECTIVE)
        inv_len = 1.0 / max(L, 1.0)
        for s, age in self._rings:
            t = age / self.RING_LIFE
            ws = width + (end_width - width) * min(1.0, s * inv_len)
            out.rings.append(Ring(center=(o[0] + d[0] * s, o[1] + d[1] * s), radius=ws * (1.25 + 0.6 * t),
                                  thickness=max(0.5, 0.22 * ws), palette=pal,
                                  intensity=0.9 * (1.0 - t) ** 1.3 * fade,
                                  refraction=3.0 * ss * p1 * (1.0 - t), noise=0.35, squash=squash, time=age))
        if not self._ending and self._progress > 0.3:
            lv = self._visible
            nx, ny = -d[1], d[0]
            for slot in self._arcs:
                if not slot.visible:
                    continue
                s1 = slot.p0 * lv
                s2 = min(lv, s1 + slot.p1 * lv)
                if s2 - s1 < 6.0 * ss:
                    continue
                off1 = slot.p2 * slot.p3 * (width + (end_width - width) * s1 * inv_len)
                off2 = slot.p2 * slot.p3 * (width + (end_width - width) * s2 * inv_len)
                a = (o[0] + d[0] * s1 + nx * off1, o[1] + d[1] * s1 + ny * off1)
                b = (o[0] + d[0] * s2 + nx * off2, o[1] + d[1] * s2 + ny * off2)
                sys._add_arc(out, slot, a, b, slot.width, (1.4 + 0.8 * p1) * slot.gain, 1.3)
        lights.append((o[0], o[1], max(7.0 * width, 0.3 * sys._scene_h), (1.2 + p) * fade))
        lv = self._visible
        if lv > 2.0 * width:
            for f in (0.4, 0.8):
                s = f * lv
                lights.append((o[0] + d[0] * s, o[1] + d[1] * s, 5.0 * width, 0.6 * fade * self._progress))

    def _finishing(self) -> bool:
        return not self._alive or self._ending

    def _finish(self) -> None:
        self.end()

    def _rescale(self, sx: float, sy: float) -> None:
        self._origin = (self._origin[0] * sx, self._origin[1] * sy)
        self._target_origin = (self._target_origin[0] * sx, self._target_origin[1] * sy)
        self._base_width *= sy
        # Map the direction like the positions (an aspect change turns it) and scale the
        # ring distances by the length change along it, so points on the beam stay put.
        dx, dy = self.direction
        along = math.hypot(dx * sx, dy * sy)
        self._angle = math.atan2(dy * sy, dx * sx)
        self._target_angle = math.atan2(math.sin(self._target_angle) * sy, math.cos(self._target_angle) * sx)
        for ring in self._rings:
            ring[0] *= along
        self._update_geometry()


