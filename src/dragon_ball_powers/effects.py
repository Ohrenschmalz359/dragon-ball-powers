def _sanitize_quality(preset: Any) -> QualityPreset | None:
    """``preset`` itself, a copy with out-of-range numbers clamped, or ``None`` when unusable.

    The presets of :data:`~dragon_ball_powers.primitives.QUALITY_PRESETS` are returned
    unchanged; the clamps only protect against hand-made presets (a huge ``arc_count``
    would mean thousands of bolts per frame).
    """
    try:
        budget = float(preset.particle_budget)
        arcs = float(preset.arc_count)
        res = float(preset.aura_resolution)
    except (AttributeError, TypeError, ValueError, OverflowError):
        return None
    if not (math.isfinite(budget) and math.isfinite(arcs) and math.isfinite(res)):
        return None
    fixed: dict[str, int] = {}
    if not 1.0 <= budget <= MAX_PARTICLE_BUDGET or budget != int(budget):
        fixed["particle_budget"] = int(clamp(budget, 1.0, float(MAX_PARTICLE_BUDGET)))
    if not 0.0 <= arcs <= MAX_ARC_COUNT or arcs != int(arcs):
        fixed["arc_count"] = int(clamp(arcs, 0.0, float(MAX_ARC_COUNT)))
    if not 16.0 <= res <= 2048.0 or res != int(res):
        fixed["aura_resolution"] = int(clamp(res, 16.0, 2048.0))
    if not fixed:
        return preset
    try:
        return dataclasses.replace(preset, **fixed)
    except (TypeError, ValueError):
        return None


def _sanitize_size(size: Any, fallback: tuple[int, int] = (1280, 720)) -> tuple[int, int]:
    try:
        w = int(round(float(size[0])))
        h = int(round(float(size[1])))
    except (TypeError, ValueError, IndexError, OverflowError):
        log.warning("Invalid scene size %r; using %s", size, fallback)
        return fallback
    if w < 16 or h < 16 or w > 16384 or h > 16384:
        log.warning("Implausible scene size %r; using %s", size, fallback)
        return fallback
    return (w, h)


def _mask_to_u8(mask: Any) -> np.ndarray | None:
    """Normalise a person mask to a contiguous (h, w) uint8 0..255 array."""
    try:
        m = np.asarray(mask)
    except Exception:  # noqa: BLE001 - any odd object simply is not a mask
        return None
    if m.ndim == 3 and m.shape[2] >= 1:
        m = m[:, :, 0]
    if m.ndim != 2 or m.shape[0] < 2 or m.shape[1] < 2:
        return None
    if m.dtype == np.uint8:
        return np.ascontiguousarray(m)
    if m.dtype == np.bool_:
        return m.astype(np.uint8) * np.uint8(255)
    if m.dtype.kind not in "biuf":
        return None
    mf = np.nan_to_num(m.astype(np.float32), nan=0.0, posinf=0.0, neginf=0.0)
    if mf.size and float(mf.max()) <= 1.0 + 1e-6:
        mf *= 255.0
    return np.clip(mf, 0.0, 255.0).astype(np.uint8)


_CHECK_FIELDS: dict[type, tuple[str, ...]] = {}


def _value_finite(v: Any) -> bool:
    if isinstance(v, (float, np.floating)):
        return math.isfinite(v)
    if isinstance(v, tuple):
        return all(_value_finite(x) for x in v)
    if isinstance(v, np.ndarray):
        return v.dtype.kind != "f" or bool(np.isfinite(v).all())
    return True


def _generic_finite(p: Any) -> bool:
    names = _CHECK_FIELDS.get(type(p))
    if names is None:
        names = tuple(f.name for f in dataclasses.fields(p) if f.name not in ("palette", "mask", "shape"))
        _CHECK_FIELDS[type(p)] = names
    return all(_value_finite(getattr(p, n)) for n in names)


# Fast per-type checks: a sum is non-finite iff one of its terms is NaN/inf (or the values
# are absurdly large, which is just as unusable). Arc points are finite by construction
# once their endpoints are (see EffectSystem._add_arc), so only the endpoints are summed.
_FAST_FINITE: dict[type, Any] = {
    Orb: lambda p: math.isfinite(p.center[0] + p.center[1] + p.radius + p.intensity + p.charge + p.time + p.seed
                                 + p.swirl + p.instability + p.flare + p.squash[0] + p.squash[1] + p.rotation),
    Beam: lambda p: math.isfinite(p.origin[0] + p.origin[1] + p.direction[0] + p.direction[1] + p.length + p.width
                                  + p.end_width + p.intensity + p.time + p.seed + p.head_radius + p.turbulence
                                  + p.flow_speed + p.fade + p.dissolve),
    FrontalBeam: lambda p: math.isfinite(p.center[0] + p.center[1] + p.radius + p.intensity + p.time + p.seed
                                         + p.streaks + p.fade + p.dissolve),
    Arc: lambda p: math.isfinite(p.width + p.intensity + p.glow + float(p.points[0, 0]) + float(p.points[0, 1])
                                 + float(p.points[-1, 0]) + float(p.points[-1, 1])),
    Ring: lambda p: math.isfinite(p.center[0] + p.center[1] + p.radius + p.thickness + p.intensity + p.refraction
                                  + p.noise + p.squash[0] + p.squash[1] + p.time),
    Ribbon: lambda p: math.isfinite(float(p.points.sum()) + float(p.widths.sum()) + float(p.intensities.sum())),
    Flash: lambda p: math.isfinite(p.intensity + p.radius + sum(p.color)
                                   + (0.0 if p.center is None else p.center[0] + p.center[1])),
    Light: lambda p: math.isfinite(p.position[0] + p.position[1] + p.radius + p.intensity + sum(p.color)),
    Aura: lambda p: math.isfinite(p.intensity + p.time + p.flame_height + p.turbulence + p.flicker),
}


def _primitive_finite(p: Any) -> bool:
    check = _FAST_FINITE.get(type(p))
    try:
        return bool(check(p)) if check is not None else _generic_finite(p)
    except (TypeError, IndexError, ValueError, AttributeError):
        return _generic_finite(p)


