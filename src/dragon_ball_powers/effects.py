class _LightPulse(_Effect):
    """A short decaying light (explosions, releases)."""

    def __init__(self, system: EffectSystem, pos: Vec2, radius: float, intensity: float, duration: float) -> None:
        super().__init__(system)
        self._pos = pos
        self._radius = radius
        self._intensity = intensity
        self._duration = max(duration, 0.02)

    def _step(self, dt: float) -> None:
        super()._step(dt)
        if self._age >= self._duration:
            self._kill()

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        u = clamp(self._age / self._duration)
        lights.append((self._pos[0], self._pos[1], self._radius, self._intensity * (1.0 - u) ** 2))

    def _rescale(self, sx: float, sy: float) -> None:
        self._pos = (self._pos[0] * sx, self._pos[1] * sy)
        self._radius *= sy


class _RadialArcs(_Effect):
    """Lightning bolts shooting radially out of an explosion for a short time."""

    def __init__(self, system: EffectSystem, center: Vec2, radius: float, count: int, duration: float,
                 intensity: float) -> None:
        super().__init__(system)
        self._center = center
        self._radius = radius
        self._duration = max(duration, 0.02)
        self._intensity = intensity
        rng = system.rng
        base = float(rng.uniform(0.0, TAU))
        reach = 0.6 * system._scene_h
        self._slots: list[_ArcSlot] = []
        for i in range(max(0, count)):
            slot = _ArcSlot()
            slot.p2 = base + TAU * i / max(count, 1) + float(rng.uniform(-0.2, 0.2))   # home angle
            slot.p0 = slot.p2
            slot.p1 = min(float(rng.uniform(2.6, 5.5)) * radius, max(reach, 1.5 * radius))  # outer radius
            system._regen_arc(slot, slot.p1, jaggedness=0.28, branch_prob=0.25, visible_prob=0.9)
            self._slots.append(slot)

    def _step(self, dt: float) -> None:
        super()._step(dt)
        if self._age >= self._duration:
            self._kill()
            return
        sys = self._sys
        for slot in self._slots:
            slot.timer -= dt
            if slot.timer <= 0.0:
                slot.p0 = slot.p2 + float(sys.rng.uniform(-0.12, 0.12))
                sys._regen_arc(slot, slot.p1, jaggedness=0.28, branch_prob=0.25, visible_prob=0.9)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        fade = 1.0 - clamp(self._age / self._duration)
        cx, cy = self._center
        inner = 0.45 * self._radius
        for slot in self._slots:
            if not slot.visible:
                continue
            c, s = math.cos(slot.p0), math.sin(slot.p0)
            a = (cx + c * inner, cy + s * inner)
            b = (cx + c * slot.p1, cy + s * slot.p1)
            self._sys._add_arc(out, slot, a, b, slot.width * 1.15, self._intensity * slot.gain * fade, 1.4)

    def _rescale(self, sx: float, sy: float) -> None:
        self._center = (self._center[0] * sx, self._center[1] * sy)
        self._radius *= sy
        for slot in self._slots:
            slot.p1 *= sy


class _LateralBlast(_Effect):
    """Ki blast flying across the image plane, exploding at the scene edge."""

    TRAIL_TIME = 0.12

    def __init__(self, system: EffectSystem, origin: Vec2, direction: Vec2, radius: float, power: float) -> None:
        super().__init__(system)
        self._origin = origin
        self._dir = direction
        self._radius = radius
        self._power = power
        self._dist = 0.0
        self._pos: Vec2 = origin
        ss = system.scene_scale
        system.flash(0.5 + 0.4 * power, center=origin, radius=5.0 * radius, duration=0.15)
        system.shake(0.006 + 0.006 * min(power, 1.0), 0.2)
        system._spray(_SPARK, origin, int(40 * system._spark_density), (200.0 * ss, 700.0 * ss),
                      direction=(-direction[0], -direction[1]), spread=2.4, inner=0.8 * radius,
                      size=(0.9 * ss, 1.8 * ss), life=(0.15, 0.35), drag=4.0, intensity=(2.2, 0.3), replace=True)

    @property
    def speed(self) -> float:
        return 1.6 * self._sys._scene_w

    def _step(self, dt: float) -> None:
        super()._step(dt)
        sys = self._sys
        exit_d = _ray_exit(self._origin, self._dir, sys._scene_w, sys._scene_h)
        self._dist += self.speed * dt
        if self._dist >= exit_d:
            x = clamp(self._origin[0] + self._dir[0] * exit_d, 0.0, float(sys._scene_w))
            y = clamp(self._origin[1] + self._dir[1] * exit_d, 0.0, float(sys._scene_h))
            self._pos = (x, y)
            self._explode()
            return
        self._pos = (self._origin[0] + self._dir[0] * self._dist, self._origin[1] + self._dir[1] * self._dist)

    def _explode(self) -> None:
        sys = self._sys
        ss = sys.scene_scale
        h = sys._scene_h
        c = self._pos
        R = self._radius
        p = self._power
        p1 = min(p, 1.0)
        back = (-self._dir[0], -self._dir[1])   # debris flies back into the picture
        sys.flash(1.6 + p, center=c, radius=max(0.55 * h, 6.0 * R), duration=0.3)
        sys.flash(0.25 + 0.2 * p1, duration=0.2)
        sys.shockwave(c, R, p1)
        sys._spray(_SPARK, c, int((120 + 160 * p1) * sys._spark_density), (400.0 * ss, 1600.0 * ss), direction=back,
                   spread=3.6, inner=0.6 * R, size=(1.0 * ss, 2.4 * ss), life=(0.3, 0.75), drag=2.6, grav=150.0 * ss,
                   intensity=(2.6, 0.3), replace=True)
        sys._spray(_EMBER, c, int(40 * sys._spark_density), (100.0 * ss, 450.0 * ss), direction=back, spread=3.4,
                   inner=0.5 * R, size=(1.0 * ss, 2.2 * ss), life=(0.6, 1.3), drag=1.6, grav=-60.0 * ss,
                   intensity=(2.0, 0.4), colors=(ROLE_INNER, ROLE_CORE), flicker=0.35, replace=True)
        sys._spray(_SMOKE, c, 8, (20.0 * ss, 90.0 * ss), inner=0.6 * R, size=(0.6 * R, 1.0 * R), size_end=2.2,
                   life=(0.6, 1.1), drag=1.5, grav=-30.0 * ss, intensity=(0.3, 0.0), colors=(ROLE_SMOKE, ROLE_OUTER),
                   mix=(0.0, 0.3), fade_in=0.25, replace=True)
        sys.shake(0.02 + 0.015 * p1, 0.45)
        sys._grade.pulse(2.5 * ss * p1, 0.01 + 0.01 * p1)
        sys._light_pulse(c, max(8.0 * R, 0.5 * h), 2.5 + p, 0.45)
        self._kill()

    def _emit(self, dt: float) -> None:
        if dt <= 0.0:
            return
        sys = self._sys
        ss = sys.scene_scale
        n = self._take(0, 380.0 * sys._density * dt)
        if n:
            spd = self.speed
            base = (-self._dir[0] * 0.25 * spd, -self._dir[1] * 0.25 * spd)
            sys._spray(_SPARK, self._pos, n, (60.0 * ss, 260.0 * ss), inner=0.9 * self._radius, base_vel=base,
                       size=(0.9 * ss, 1.8 * ss), life=(0.12, 0.3), drag=5.0, intensity=(2.2, 0.3),
                       age_spread=dt, replace=False)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        sys = self._sys
        pal = sys._palette
        R = self._radius
        p = self._power
        dx, dy = self._dir
        out.orbs.append(Orb(center=self._pos, radius=R, palette=pal, intensity=2.0 + p, charge=1.0, time=self._age,
                            seed=self._seed, swirl=2.0, instability=0.6, flare=0.5 + 0.5 * min(p, 1.0),
                            squash=(1.25, 0.85), rotation=math.atan2(dy, dx)))
        if sys._settings.motion_trails:
            trail = min(self._dist, self.speed * self.TRAIL_TIME)
            if trail > 2.0:
                s = np.linspace(0.0, 1.0, 12, dtype=np.float32)
                back = trail * (1.0 - s)
                pts = np.empty((12, 2), np.float32)
                pts[:, 0] = self._pos[0] - dx * back
                pts[:, 1] = self._pos[1] - dy * back
                widths = (R * 0.85 * (0.2 + 0.8 * s)).astype(np.float32)
                intens = ((1.2 + 0.5 * p) * s ** 1.3).astype(np.float32)
                out.ribbons.append(Ribbon(points=pts, widths=widths, intensities=intens, palette=pal))
        lights.append((self._pos[0], self._pos[1], 5.0 * R, 1.5 + p))

    def _rescale(self, sx: float, sy: float) -> None:
        self._origin = (self._origin[0] * sx, self._origin[1] * sy)
        self._pos = (self._pos[0] * sx, self._pos[1] * sy)
        self._radius *= sy
        # Exact mapping of the flight line: pos = origin + dir * dist holds after the rescale.
        dx, dy = self._dir
        along = math.hypot(dx * sx, dy * sy)
        if along > 1e-9:
            self._dir = (dx * sx / along, dy * sy / along)
            self._dist *= along


class _FrontalBlast(_Effect):
    """Ki blast flying at the camera: grows exponentially, then hits the lens."""

    FLIGHT_TIME = 0.35

    def __init__(self, system: EffectSystem, origin: Vec2, radius: float, power: float) -> None:
        super().__init__(system)
        h = system._scene_h
        self._origin = origin
        self._center: Vec2 = origin
        self._power = power
        self._r0 = max(radius, 4.0 * system.scene_scale)
        self._radius = self._r0
        self._k = math.log(max(0.9 * h / self._r0, 1.0001)) / self.FLIGHT_TIME
        system.flash(0.5 + 0.4 * power, center=origin, radius=5.0 * self._r0, duration=0.15)
        system.shake(0.008, 0.2)

    def _step(self, dt: float) -> None:
        super()._step(dt)
        sys = self._sys
        h = sys._scene_h
        self._radius = self._r0 * math.exp(min(self._k * self._age, 40.0))
        u = smoothstep(0.0, 1.0, self._age / self.FLIGHT_TIME)
        # drift towards the image centre so the hit fills the screen
        cx, cy = 0.5 * sys._scene_w, 0.5 * h
        k = 0.35 * u
        self._center = (self._origin[0] + (cx - self._origin[0]) * k, self._origin[1] + (cy - self._origin[1]) * k)
        if self._radius >= 0.9 * h or self._age > 2.0 * self.FLIGHT_TIME:
            self._impact()

    def _impact(self) -> None:
        sys = self._sys
        ss = sys.scene_scale
        h = sys._scene_h
        p = self._power
        p1 = min(p, 1.0)
        c = self._center
        dens = sys._spark_density
        sys._add_flash(0.9, None, 0.0, 0.35, tint=0.0)         # white lens hit (brief)
        sys.flash(1.5 + p, center=c, radius=1.2 * h, duration=0.35)
        sys.shake(0.035, 0.6)
        sys.shockwave(c, 0.25 * h, 1.0)
        sys._spray(_SPARK, c, int((200 + 100 * p1) * dens), (0.8 * h, 2.4 * h), inner=0.3 * h,
                   size=(1.6 * ss, 3.6 * ss), life=(0.25, 0.6), drag=1.5, intensity=(3.0, 0.4), replace=True)
        sys._spray(_EMBER, c, int(80 * dens), (0.3 * h, 1.0 * h), inner=0.25 * h, size=(1.4 * ss, 3.0 * ss),
                   life=(0.5, 1.1), drag=1.4, grav=80.0 * ss, intensity=(2.2, 0.3), colors=(ROLE_INNER, ROLE_CORE),
                   flicker=0.3, replace=True)
        sys._spray(_SMOKE, c, 10, (60.0 * ss, 200.0 * ss), inner=0.3 * h, size=(0.12 * h, 0.2 * h), size_end=1.8,
                   life=(0.6, 1.0), drag=1.2, intensity=(0.3, 0.0), colors=(ROLE_SMOKE, ROLE_INNER),
                   mix=(0.0, 0.4), fade_in=0.2, replace=True)
        sys._grade.pulse(3.0 * ss, 0.03)
        sys._light_pulse(c, 1.5 * h, 3.0 + p, 0.5)
        self._kill()

    def _emit(self, dt: float) -> None:
        if dt <= 0.0:
            return
        sys = self._sys
        n = self._take(0, 260.0 * sys._density * dt)
        if n:
            sys._emit_streaks(self._center, 0.8 * self._radius, n, dt)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        sys = self._sys
        u = clamp(self._age / self.FLIGHT_TIME)
        p = self._power
        R = self._radius
        out.orbs.append(Orb(center=self._center, radius=R, palette=sys._palette, intensity=2.0 + p + 1.5 * u,
                            charge=1.0, time=self._age, seed=self._seed, swirl=2.0 + u, instability=0.6 + 0.4 * u,
                            flare=1.0))
        lights.append((self._center[0], self._center[1], 4.0 * R, 2.0 + p + u))

    def _rescale(self, sx: float, sy: float) -> None:
        self._origin = (self._origin[0] * sx, self._origin[1] * sy)
        self._center = (self._center[0] * sx, self._center[1] * sy)
        self._r0 *= sy
        self._radius *= sy


