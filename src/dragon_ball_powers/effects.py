class FrontalBeamEffect(_Effect):
    """A Kamehameha fired towards the camera, seen end-on (create with :meth:`EffectSystem.create_frontal_beam`).

    Read-only state: ``alive``, ``center``, ``radius``, ``power``. Steer with :meth:`set`;
    :meth:`end` fades and dissolves it over 0.5 s.
    """

    transient = False
    GROW_TIME = 0.25
    END_TIME = 0.5
    CENTER_RATE = 30.0
    POWER_RATE = 8.0
    RING_INTERVAL = 0.2
    RING_LIFE = 0.5

    def __init__(self, system: EffectSystem, center: Vec2, radius: float, power: float) -> None:
        super().__init__(system)
        self._center: Vec2 = center
        self._target: Vec2 = center
        self._r0 = radius
        self._radius = radius
        self._power = power
        self._target_power = power
        self._ending = False
        self._end_age = 0.0
        self._ring_timer = 0.0
        self._rings: list[float] = []   # ages
        q = max(0, int(system._quality.arc_count))
        self._arcs = [_ArcSlot() for _ in range(min(3, max(1, q // 2)) if q > 0 else 0)]
        self._impact()

    @property
    def center(self) -> Vec2:
        return self._center

    @property
    def radius(self) -> float:
        return self._radius

    @property
    def power(self) -> float:
        return self._power

    @property
    def target_radius(self) -> float:
        """Sustained cross-section radius: 0.27 x scene_h x (0.8 + 0.4 x power) (power <= 1.5).

        Big enough to read as "the beam is coming at you", small enough that the user
        stays visible around it."""
        return 0.27 * self._sys._scene_h * (0.8 + 0.4 * self._power)

    def set(self, center: Vec2, power: float | None = None) -> None:
        """Steer the beam centre (smoothed) and optionally its power."""
        if not self._alive or self._ending:
            return
        sys = self._sys
        c = sys._vec(center, "frontal beam center")
        if c is not None:
            self._target = sys._clamp_pos(c)
        if power is not None:
            self._target_power = sys._power_value(power, self._target_power)

    def end(self) -> None:
        """Stop firing: fade + dissolve over 0.5 s, then die."""
        if self._alive and not self._ending:
            self._ending = True
            self._end_age = 0.0

    def _end_fraction(self) -> float:
        return clamp(self._end_age / self.END_TIME) if self._ending else 0.0

    def _impact(self) -> None:
        sys = self._sys
        ss = sys.scene_scale
        h = sys._scene_h
        p = self._power
        p1 = min(p, 1.0)
        c = self._center
        sys.flash(1.0 + 0.6 * p, duration=0.35)                     # big uniform flash
        sys.flash(0.9 + 0.4 * p, center=c, radius=0.6 * h, duration=0.22)
        sys.shake(0.03, 0.5)
        sys._grade.pulse(3.0 * ss, 0.02 + 0.01 * p1)
        sys.shockwave(c, max(self._r0, 10.0 * ss) * 1.5, 0.6 + 0.4 * p1)
        n = int((80 + 120 * p1) * sys._spark_density)
        sys._spray(_SPARK, c, n, (600.0 * ss, 1800.0 * ss), inner=0.5 * self._r0, size=(1.2 * ss, 2.6 * ss),
                   life=(0.25, 0.6), drag=2.0, intensity=(2.6, 0.4), replace=True)

    def _step(self, dt: float) -> None:
        super()._step(dt)
        sys = self._sys
        if self._ending:
            self._end_age += dt
            if self._end_age >= self.END_TIME:
                self._kill()
                return
        else:
            self._center = damp_vec(self._center, self._target, self.CENTER_RATE, dt)
            self._power = damp(self._power, self._target_power, self.POWER_RATE, dt)
            sys._shaker.request_sustain(0.006 * (0.6 + 0.4 * min(self._power, 1.0)))
        target = self.target_radius
        if self._age < self.GROW_TIME:
            self._radius = self._r0 + (target - self._r0) * ease_out_cubic(self._age / self.GROW_TIME)
        else:
            self._radius = damp(self._radius, target, 6.0, dt)
        if not self._ending:
            self._ring_timer -= dt
            if self._ring_timer <= 0.0:
                self._ring_timer = self.RING_INTERVAL * float(sys.rng.uniform(0.85, 1.15))
                self._rings.append(0.0)
        self._rings = [a + dt for a in self._rings if a + dt < self.RING_LIFE]
        if not self._ending:
            rng = sys.rng
            for slot in self._arcs:
                slot.timer -= dt
                if slot.timer <= 0.0:
                    slot.p0 = float(rng.uniform(0.0, TAU))
                    slot.p1 = float(rng.uniform(0.4, 1.0))
                    chord = 2.0 * self._radius * math.sin(0.5 * slot.p1)
                    sys._regen_arc(slot, chord, jaggedness=0.28, bow=-0.18, visible_prob=0.8)

    def _emit(self, dt: float) -> None:
        if dt <= 0.0:
            return
        sys = self._sys
        ss = sys.scene_scale
        dens = sys._density
        live = 1.0 - self._end_fraction()
        R = self._radius
        n = self._take(0, 360.0 * dens * live * dt)
        if n:
            sys._emit_streaks(self._center, R, n, dt)
        n = self._take(1, 70.0 * dens * live * dt)
        if n:
            r = sys.rng.random((6, n), dtype=np.float32)
            ang = r[0] * np.float32(TAU)
            dirs = np.stack((np.cos(ang), np.sin(ang)), axis=1)
            pos = np.asarray(self._center, np.float32) + dirs * (R * (0.1 + 0.5 * r[1]))[:, None]
            vel = dirs * ((150.0 + 250.0 * r[2]) * ss)[:, None]
            sys._particles.emit(_GLOW, pos, vel, 0.35 + 0.25 * r[3], 3.0 * ss, (18.0 + 16.0 * r[4]) * ss,
                                col_a=ROLE_INNER, col_b=ROLE_CORE, col_t=r[5], int0=0.15, int1=0.8, drag=-3.0,
                                fade_in=0.2, age=r[3] * dt, replace=False)
        if self._ending:
            n = self._take(2, 200.0 * dens * live * dt)
            if n:
                sys._spray(_SMOKE, self._center, n, (40.0 * ss, 160.0 * ss), inner=0.9 * R,
                           size=(0.12 * R, 0.25 * R), size_end=2.0, life=(0.35, 0.6), drag=1.5,
                           intensity=(0.35, 0.0), colors=(ROLE_SMOKE, ROLE_INNER), mix=(0.0, 0.5), fade_in=0.2,
                           replace=False)

    def _collect(self, out: RenderList, lights: list[tuple[float, float, float, float]]) -> None:
        sys = self._sys
        pal = sys._palette
        ss = sys.scene_scale
        u = self._end_fraction()
        fade = 1.0 - u
        p = self._power
        p1 = min(p, 1.0)
        pulse = 1.0 + 0.03 * math.sin(TAU * 6.0 * self._age + self._seed)
        R = self._radius * pulse * (1.0 + 0.12 * u)
        cx, cy = self._center
        out.frontal_beams.append(FrontalBeam(center=self._center, radius=R, palette=pal, intensity=1.8 + p,
                                             time=self._age, seed=self._seed, streaks=1.0, fade=fade, dissolve=u))
        for age in self._rings:
            t = age / self.RING_LIFE
            out.rings.append(Ring(center=self._center, radius=R * (0.55 + 1.7 * ease_out_cubic(t)),
                                  thickness=max(1.0, 0.1 * R * (1.0 - 0.6 * t)), palette=pal,
                                  intensity=(1.0 - t) ** 1.5 * fade, refraction=6.0 * ss * p1 * (1.0 - t),
                                  noise=0.4, time=age))
        if not self._ending:
            rr = 1.02 * R
            for slot in self._arcs:
                if not slot.visible:
                    continue
                a = (cx + math.cos(slot.p0) * rr, cy + math.sin(slot.p0) * rr)
                b = (cx + math.cos(slot.p0 + slot.p1) * rr, cy + math.sin(slot.p0 + slot.p1) * rr)
                sys._add_arc(out, slot, a, b, slot.width, (1.4 + 0.6 * p1) * slot.gain, 1.2)
        lights.append((cx, cy, 3.0 * R, (2.0 + p) * fade))

    def _finishing(self) -> bool:
        return not self._alive or self._ending

    def _finish(self) -> None:
        self.end()

    def _rescale(self, sx: float, sy: float) -> None:
        self._center = (self._center[0] * sx, self._center[1] * sy)
        self._target = (self._target[0] * sx, self._target[1] * sy)
        self._r0 *= sy
        self._radius *= sy


